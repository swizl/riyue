bool 调试模式 = false;

int 测试通过 = 0;
int 测试失败 = 0;

void 断言(bool 条件, const std::string& 名称) {
    if (条件) {
        std::cout << "  [通过] " << 名称 << std::endl;
        测试通过++;
    } else {
        std::cout << "  [失败] " << 名称 << std::endl;
        测试失败++;
    }
}

