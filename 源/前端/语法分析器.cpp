std::vector<std::unique_ptr<语句>> 语法分析器::解析代码块() {
    期望(标记类型::左花括号, "应有'{'");
    std::vector<std::unique_ptr<语句>> 语句列表;
    while (_当前标记.类型 != 标记类型::右花括号 && _当前标记.类型 != 标记类型::文件结束) {
        语句列表.push_back(解析语句());
    }
    期望(标记类型::右花括号, "应有'}'闭合");
    return 语句列表;
}

std::unique_ptr<语句> 语法分析器::解析语句() {
    标记 当前 = _当前标记;

    // 新语法：值 = 变量名; (值在左，变量在右)
    // 先解析一个表达式，然后检查是否跟着 = 标识符 ;
    if (当前.类型 != 标记类型::变量 && 当前.类型 != 标记类型::常量 &&
        当前.类型 != 标记类型::如果 && 当前.类型 != 标记类型::否则 &&
        当前.类型 != 标记类型::循环 && 当前.类型 != 标记类型::当 &&
        当前.类型 != 标记类型::做 && 当前.类型 != 标记类型::中断 &&
        当前.类型 != 标记类型::继续 && 当前.类型 != 标记类型::返回 &&
        当前.类型 != 标记类型::匹配 &&
        当前.类型 != 标记类型::遍历 && 当前.类型 != 标记类型::结构体 &&
        当前.类型 != 标记类型::枚举 && 当前.类型 != 标记类型::导入 &&
        当前.类型 != 标记类型::左花括号) {
        // 尝试解析为 表达式 = 标识符; 的形式
        size_t 保存位置 = _词法分析器.获取位置();
        int 保存行号 = _词法分析器.获取当前行();
        标记 保存标记 = _当前标记;

        try {
            auto 值表达式 = 解析表达式();
            if (_当前标记.类型 == 标记类型::等于) {
                前进();
                
                // 检查是否为解构赋值 值 = (变量1, 变量2, ...)
                if (_当前标记.类型 == 标记类型::左括号) {
                    前进();
                    std::vector<std::string> 变量名列表;
                    if (_当前标记.类型 == 标记类型::标识符) {
                        变量名列表.push_back(_当前标记.值);
                        前进();
                        while (_当前标记.类型 == 标记类型::逗号) {
                            前进();
                            期望类型(标记类型::标识符, "解构赋值变量名应为标识符");
                            变量名列表.push_back(_当前标记.值);
                            前进();
                        }
                    }
                    期望(标记类型::右括号, "解构赋值后应有')'");
                    期望(标记类型::分号, "赋值后应有';'");
                    return std::make_unique<解构赋值语句>(std::move(变量名列表), std::move(值表达式));
                }
                
                // 期望标识符（变量名）
                期望类型(标记类型::标识符, "赋值目标应为变量名");
                std::string 变量名 = _当前标记.值;
                前进();

                // 检查是否为成员赋值 值 = 对象.成员
                if (_当前标记.类型 == 标记类型::句号) {
                    前进();
                    期望类型(标记类型::标识符, "成员名应为标识符");
                    std::string 成员名 = _当前标记.值;
                    前进();
                    期望(标记类型::分号, "赋值后应有';'");
                    return std::make_unique<赋值语句>(变量名 + "." + 成员名, std::move(值表达式));
                }

                // 检查是否为下标赋值 值 = 变量名[索引]
                if (_当前标记.类型 == 标记类型::左方括号) {
                    前进();
                    auto 索引 = 解析表达式();
                    期望(标记类型::右方括号, "下标后应有']'");
                    期望(标记类型::分号, "赋值后应有';'");
                    return std::make_unique<下标赋值语句>(变量名, std::move(索引), std::move(值表达式));
                }

                // 可选的类型注解
                if (_当前标记.类型 == 标记类型::冒号) {
                    前进();
                    if (_当前标记.类型 == 标记类型::整数类型 || _当前标记.类型 == 标记类型::浮点类型 ||
                        _当前标记.类型 == 标记类型::布尔类型 || _当前标记.类型 == 标记类型::标识符) {
                        前进();
                    }
                }

                期望(标记类型::分号, "赋值后应有';'");
                // 需要在代码生成阶段判断是声明还是赋值
                // 这里使用变量声明，代码生成器会处理已存在的情况
                return std::make_unique<变量声明>(变量名, std::move(值表达式));
            }
            // 如果不是赋值，则作为表达式语句
            期望(标记类型::分号, "表达式后应有';'");
            return std::make_unique<表达式语句>(std::move(值表达式));
        } catch (...) {
            // 回溯并尝试原来的解析方式
            _词法分析器.设置位置(保存位置);
            _词法分析器.设置当前行(保存行号);
            _当前标记 = 保存标记;
        }
    }

    if (当前.类型 == 标记类型::标识符) {
        std::string 变量名 = 当前.值;
        前进();
        if (_当前标记.类型 == 标记类型::左方括号) {
            前进();
            auto 索引 = 解析表达式();
            期望(标记类型::右方括号, "下标后应有']'");
            期望(标记类型::等于, "下标后应有'='");
            auto 值 = 解析表达式();
            期望(标记类型::分号, "赋值后应有';'");
            return std::make_unique<下标赋值语句>(变量名, std::move(索引), std::move(值));
        }
        if (_当前标记.类型 == 标记类型::句号) {
            // 成员赋值: 对象.成员 = 值
            前进();
            期望类型(标记类型::标识符, "成员名应为标识符");
            std::string 成员名 = _当前标记.值;
            前进();
            期望(标记类型::等于, "成员后应有'='");
            auto 值 = 解析表达式();
            期望(标记类型::分号, "赋值后应有';'");
            // 将成员赋值转换为：对象[成员索引] = 值 (由代码生成器处理)
            return std::make_unique<赋值语句>(变量名 + "." + 成员名, std::move(值));
        }
        if (_当前标记.类型 == 标记类型::等于) {
            前进();
            auto 值 = 解析表达式();
            期望(标记类型::分号, "赋值后应有';'");
            return std::make_unique<赋值语句>(变量名, std::move(值));
        }
        if (_当前标记.类型 == 标记类型::加等于 || _当前标记.类型 == 标记类型::减等于 ||
            _当前标记.类型 == 标记类型::乘等于 || _当前标记.类型 == 标记类型::除等于 ||
            _当前标记.类型 == 标记类型::模等于 || _当前标记.类型 == 标记类型::位与等于 ||
            _当前标记.类型 == 标记类型::位或等于 || _当前标记.类型 == 标记类型::位异或等于 ||
            _当前标记.类型 == 标记类型::左移等于 || _当前标记.类型 == 标记类型::右移等于) {
            二元操作符 op;
            switch (_当前标记.类型) {
                case 标记类型::加等于: op = 二元操作符::加法; break;
                case 标记类型::减等于: op = 二元操作符::减法; break;
                case 标记类型::乘等于: op = 二元操作符::乘法; break;
                case 标记类型::除等于: op = 二元操作符::除法; break;
                case 标记类型::模等于: op = 二元操作符::取模; break;
                case 标记类型::位与等于: op = 二元操作符::位与; break;
                case 标记类型::位或等于: op = 二元操作符::位或; break;
                case 标记类型::位异或等于: op = 二元操作符::位异或; break;
                case 标记类型::左移等于: op = 二元操作符::左移; break;
                case 标记类型::右移等于: op = 二元操作符::右移; break;
                default: throw std::runtime_error("未知复合赋值");
            }
            前进();
            auto 右值 = 解析表达式();
            auto 变量引用 = std::make_unique<变量表达式>(变量名);
            auto 二元 = std::make_unique<二元运算表达式>(op, std::move(变量引用), std::move(右值));
            期望(标记类型::分号, "赋值后应有';'");
            return std::make_unique<赋值语句>(变量名, std::move(二元));
        }
        // 自增自减语句: 变量+| 或 变量-|
        if (_当前标记.类型 == 标记类型::自增 || _当前标记.类型 == 标记类型::自减) {
            bool 是自增 = (_当前标记.类型 == 标记类型::自增);
            前进();
            期望(标记类型::分号, "自增自减后应有';'");
            auto 表达式 = std::make_unique<自增自减表达式>(变量名, 是自增);
            return std::make_unique<表达式语句>(std::move(表达式));
        }
        throw std::runtime_error("标识符 '" + 变量名 + "' 后应有 '='（行 " + std::to_string(当前.行号) + "）");
    }

    if (当前.类型 == 标记类型::如果) {
        前进();
        期望(标记类型::左括号, "如果后应有'('");
        
        // 支持 if (值 = 变量名:类型; 条件) 或 if (条件)
        auto 第一个表达式 = 解析表达式();
        
        if (_当前标记.类型 == 标记类型::等于) {
            // if (值 = 变量名:类型; 条件) 形式
            前进();
            期望类型(标记类型::标识符, "赋值目标应为标识符");
            std::string 变量名 = _当前标记.值;
            前进();
            std::string 类型名;
            if (_当前标记.类型 == 标记类型::冒号) {
                前进();
                类型名 = _当前标记.值;
                前进();
            }
            期望(标记类型::分号, "初始化后应有';'");
            auto 条件 = 解析表达式();
            期望(标记类型::右括号, "如果条件后应有')'");
            auto then块 = 解析代码块();
            
            std::vector<否则如果分支> 否则如果列表;
            while (_当前标记.类型 == 标记类型::否则如果) {
                前进();
                期望(标记类型::左括号, "否则如果后应有'('");
                auto elif条件 = 解析表达式();
                期望(标记类型::右括号, "否则如果条件后应有')'");
                auto elif主体 = 解析代码块();
                否则如果分支 分支;
                分支.条件 = std::move(elif条件);
                分支.主体 = std::move(elif主体);
                否则如果列表.push_back(std::move(分支));
            }
            
            std::vector<std::unique_ptr<语句>> else块;
            if (_当前标记.类型 == 标记类型::否则) {
                前进();
                else块 = 解析代码块();
            }
            auto 初始化 = std::make_unique<变量声明>(变量名, std::move(第一个表达式));
            return std::make_unique<如果语句>(std::move(初始化), std::move(条件), std::move(then块), std::move(否则如果列表), std::move(else块));
        } else {
            // if (条件) 形式
            期望(标记类型::右括号, "如果条件后应有')'");
            auto then块 = 解析代码块();
            
            std::vector<否则如果分支> 否则如果列表;
            while (_当前标记.类型 == 标记类型::否则如果) {
                前进();
                期望(标记类型::左括号, "否则如果后应有'('");
                auto elif条件 = 解析表达式();
                期望(标记类型::右括号, "否则如果条件后应有')'");
                auto elif主体 = 解析代码块();
                否则如果分支 分支;
                分支.条件 = std::move(elif条件);
                分支.主体 = std::move(elif主体);
                否则如果列表.push_back(std::move(分支));
            }
            
            std::vector<std::unique_ptr<语句>> else块;
            if (_当前标记.类型 == 标记类型::否则) {
                前进();
                else块 = 解析代码块();
            }
            return std::make_unique<如果语句>(std::move(第一个表达式), std::move(then块), std::move(否则如果列表), std::move(else块));
        }
    }

    if (当前.类型 == 标记类型::循环) {
        前进();
        if (_当前标记.类型 == 标记类型::左括号) {
            前进();
            
            // 检查是否为范围循环: 循环 (变量名: 开始, 结束 [, 步长])
            if (_当前标记.类型 == 标记类型::标识符) {
                // 保存位置以便回溯
                size_t 保存位置 = _词法分析器.获取位置();
                int 保存行号 = _词法分析器.获取当前行();
                标记 保存标记 = _当前标记;
                
                std::string 循环变量 = _当前标记.值;
                前进();
                
                if (_当前标记.类型 == 标记类型::冒号) {
                    // 范围循环
                    前进();
                    auto 开始值 = 解析表达式();
                    期望(标记类型::逗号, "范围循环应有','");
                    auto 结束值 = 解析表达式();
                    
                    std::unique_ptr<表达式> 步长值;
                    if (_当前标记.类型 == 标记类型::逗号) {
                        前进();
                        步长值 = 解析表达式();
                    }
                    
                    期望(标记类型::右括号, "范围循环后应有')'");
                    auto 主体 = 解析代码块();
                    
                    // 创建: 循环 (变量 开始值; 变量 < 结束值; 变量 += 步长) { ... }
                    auto 初始化 = std::make_unique<变量声明>(循环变量, std::move(开始值));
                    
                    auto 循环变量表达式 = std::make_unique<变量表达式>(循环变量);
                    auto 条件 = std::make_unique<二元运算表达式>(二元操作符::小于, std::move(循环变量表达式), std::move(结束值));
                    
                    std::unique_ptr<语句> 步进;
                    if (步长值) {
                        步进 = std::make_unique<复合赋值语句>(循环变量, 二元操作符::加法, std::move(步长值));
                    } else {
                        auto 一 = std::make_unique<整数表达式>(1);
                        步进 = std::make_unique<复合赋值语句>(循环变量, 二元操作符::加法, std::move(一));
                    }
                    
                    return std::make_unique<循环语句>(std::move(初始化), std::move(条件), std::move(步进), std::move(主体));
                } else {
                    // 回溯，尝试解析为普通for循环
                    _词法分析器.设置位置(保存位置);
                    _词法分析器.设置当前行(保存行号);
                    _当前标记 = 保存标记;
                }
            }
            
            // 普通for循环: 循环 (初始化; 条件; 步进) { ... }
            std::unique_ptr<语句> 初始化;
            if (_当前标记.类型 != 标记类型::分号) {
                // 解析初始化语句（支持新语法：值 = 变量名）
                auto expr = 解析表达式();
                if (_当前标记.类型 == 标记类型::等于) {
                    // 新语法：值 = 变量名
                    前进();
                    期望类型(标记类型::标识符, "赋值目标应为标识符");
                    std::string 变量名 = _当前标记.值;
                    前进();
                    初始化 = std::make_unique<变量声明>(变量名, std::move(expr));
                } else {
                    初始化 = std::make_unique<表达式语句>(std::move(expr));
                }
            }
            期望(标记类型::分号, "循环初始化后应有';'");
            std::unique_ptr<表达式> 条件;
            if (_当前标记.类型 != 标记类型::分号) {
                条件 = 解析表达式();
            }
            期望(标记类型::分号, "循环条件后应有';'");
            std::unique_ptr<语句> 步进;
            if (_当前标记.类型 != 标记类型::右括号) {
                // 解析步进语句（支持 +=, -=, *=, /=）
                期望类型(标记类型::标识符, "步进应以标识符开始");
                std::string 变量名 = _当前标记.值;
                前进();
                if (_当前标记.类型 == 标记类型::加等于 || _当前标记.类型 == 标记类型::减等于 ||
                    _当前标记.类型 == 标记类型::乘等于 || _当前标记.类型 == 标记类型::除等于) {
                    二元操作符 op;
                    switch (_当前标记.类型) {
                        case 标记类型::加等于: op = 二元操作符::加法; break;
                        case 标记类型::减等于: op = 二元操作符::减法; break;
                        case 标记类型::乘等于: op = 二元操作符::乘法; break;
                        case 标记类型::除等于: op = 二元操作符::除法; break;
                        default: throw std::runtime_error("未知复合赋值");
                    }
                    前进();
                    auto 右值 = 解析表达式();
                    auto 变量引用 = std::make_unique<变量表达式>(变量名);
                    auto 二元 = std::make_unique<二元运算表达式>(op, std::move(变量引用), std::move(右值));
                    步进 = std::make_unique<赋值语句>(变量名, std::move(二元));
                } else if (_当前标记.类型 == 标记类型::等于) {
                    前进();
                    auto 值 = 解析表达式();
                    步进 = std::make_unique<赋值语句>(变量名, std::move(值));
                } else {
                    // 普通表达式（如函数调用）
                    auto expr = 解析表达式();
                    步进 = std::make_unique<表达式语句>(std::move(expr));
                }
            }
            期望(标记类型::右括号, "循环步进后应有')'");
            auto 主体 = 解析代码块();
            return std::make_unique<循环语句>(std::move(初始化), std::move(条件), std::move(步进), std::move(主体));
        } else {
            // 无限循环: 循环 { ... }
            auto 主体 = 解析代码块();
            return std::make_unique<循环语句>(std::move(主体));
        }
    }

    if (当前.类型 == 标记类型::当) {
        前进();
        期望(标记类型::左括号, "当后应有'('");
        auto 条件 = 解析表达式();
        期望(标记类型::右括号, "当条件后应有')'");
        auto 主体 = 解析代码块();
        return std::make_unique<当循环语句>(std::move(条件), std::move(主体));
    }

    if (当前.类型 == 标记类型::做) {
        前进();
        auto 主体 = 解析代码块();
        if (_当前标记.类型 == 标记类型::当) {
            前进();
            期望(标记类型::左括号, "当后应有'('");
            auto 条件 = 解析表达式();
            期望(标记类型::右括号, "当条件后应有')'");
            期望(标记类型::分号, "做-当循环后应有';'");
            return std::make_unique<做循环语句>(std::move(条件), std::move(主体), true);
        }
        if (_当前标记.类型 == 标记类型::到) {
            前进();
            期望(标记类型::左括号, "到后应有'('");
            auto 条件 = 解析表达式();
            期望(标记类型::右括号, "到条件后应有')'");
            期望(标记类型::分号, "做-到循环后应有';'");
            return std::make_unique<做循环语句>(std::move(条件), std::move(主体), false);
        }
        throw std::runtime_error("做后应有'当'或'到'");
    }

    if (当前.类型 == 标记类型::中断) {
        前进();
        期望(标记类型::分号, "中断后应有';'");
        return std::make_unique<中断语句>();
    }

    if (当前.类型 == 标记类型::继续) {
        前进();
        期望(标记类型::分号, "继续后应有';'");
        return std::make_unique<继续语句>();
    }

    if (当前.类型 == 标记类型::返回) {
        前进();
        if (_当前标记.类型 == 标记类型::分号) {
            前进();
            return std::make_unique<返回语句>(nullptr);
        }
        auto 值 = 解析表达式();
        期望(标记类型::分号, "返回后应有';'");
        return std::make_unique<返回语句>(std::move(值));
    }

    if (当前.类型 == 标记类型::匹配) {
        前进();
        期望(标记类型::左括号, "匹配后应有'('");
        auto 表达式值 = 解析表达式();
        期望(标记类型::右括号, "匹配表达式后应有')'");
        期望(标记类型::左花括号, "匹配后应有'{'");

        std::vector<匹配分支> 分支列表;
        while (_当前标记.类型 != 标记类型::右花括号 && _当前标记.类型 != 标记类型::文件结束) {
            匹配分支 分支;
            if (_当前标记.类型 == 标记类型::标识符 && _当前标记.值 == "_") {
                // 默认分支
                前进();
            } else {
                分支.条件 = 解析表达式();
            }
            期望(标记类型::箭头, "匹配分支后应有'=>'");
            期望(标记类型::左花括号, "匹配分支体应以'{'开始");
            while (_当前标记.类型 != 标记类型::右花括号 && _当前标记.类型 != 标记类型::文件结束) {
                分支.主体.push_back(解析语句());
            }
            期望(标记类型::右花括号, "匹配分支体应以'}'结束");
            分支列表.push_back(std::move(分支));
        }
        期望(标记类型::右花括号, "匹配后应有'}'");
        return std::make_unique<匹配语句>(std::move(表达式值), std::move(分支列表));
    }

    if (当前.类型 == 标记类型::遍历) {
        前进();
        期望(标记类型::左括号, "遍历后应有'('");
        期望类型(标记类型::标识符, "遍历变量应为标识符");
        std::string 变量名 = _当前标记.值;
        前进();
        期望(标记类型::冒号, "遍历变量后应有':'");
        auto 数组表达式 = 解析表达式();
        期望(标记类型::右括号, "遍历后应有')'");
        auto 主体 = 解析代码块();
        return std::make_unique<遍历语句>(变量名, std::move(数组表达式), std::move(主体));
    }

    if (当前.类型 == 标记类型::结构体) {
        前进();
        期望类型(标记类型::标识符, "结构体名应为标识符");
        std::string 名称 = _当前标记.值;
        前进();
        期望(标记类型::左花括号, "结构体后应有'{'");
        std::vector<结构体成员> 成员列表;
        std::vector<结构体方法> 方法列表;
        while (_当前标记.类型 != 标记类型::右花括号 && _当前标记.类型 != 标记类型::文件结束) {
            if (_当前标记.类型 == 标记类型::方法) {
                // 解析方法: 方法 名(参数) { ... }
                前进();
                期望类型(标记类型::标识符, "方法名应为标识符");
                std::string 方法名 = _当前标记.值;
                前进();
                期望(标记类型::左括号, "方法名后应有'('");
                std::vector<函数参数> 参数列表;
                if (_当前标记.类型 != 标记类型::右括号) {
                    参数列表 = 解析参数列表();
                }
                期望(标记类型::右括号, "方法参数后应有')'");
                auto 返回值列表 = 解析返回值列表();
                auto 主体 = 解析代码块();
                方法列表.push_back({方法名, std::move(参数列表), std::move(返回值列表), std::move(主体)});
            } else {
                // 解析成员: 名: 类型;
                期望类型(标记类型::标识符, "成员名应为标识符");
                std::string 成员名 = _当前标记.值;
                前进();
                期望(标记类型::冒号, "成员名后应有':'");
                std::string 类型名;
                if (_当前标记.类型 == 标记类型::整数类型 || _当前标记.类型 == 标记类型::浮点类型 ||
                    _当前标记.类型 == 标记类型::布尔类型 || _当前标记.类型 == 标记类型::标识符) {
                    类型名 = _当前标记.值;
                    前进();
                } else {
                    期望类型(标记类型::标识符, "成员类型应为类型名");
                }
                期望(标记类型::分号, "成员声明后应有';'");
                成员列表.push_back({成员名, 类型名});
            }
        }
        期望(标记类型::右花括号, "结构体定义应以'}'结束");
        return std::make_unique<结构体定义语句>(名称, std::move(成员列表), std::move(方法列表));
    }

    if (当前.类型 == 标记类型::左花括号) {
        auto 语句列表 = 解析代码块();
        return std::make_unique<代码块语句>(std::move(语句列表));
    }

    throw std::runtime_error("语句中意外标记 '" + 当前.值 + "'（行 " + std::to_string(当前.行号) + "）");
}

std::unique_ptr<函数> 语法分析器::解析函数() {
    期望(标记类型::函数, "函数应以'函数'开头");

    // 新语法：函数 [参数]名[返回值] {}
    // 参数和返回值的()都可以省略
    std::vector<函数参数> 参数列表;
    std::vector<std::string> 类型参数列表;

    if (_当前标记.类型 == 标记类型::小于) {
        前进();
        if (_当前标记.类型 == 标记类型::标识符) {
            类型参数列表.push_back(_当前标记.值);
            前进();
            while (_当前标记.类型 == 标记类型::逗号) {
                前进();
                期望类型(标记类型::标识符, "类型参数名应为标识符");
                类型参数列表.push_back(_当前标记.值);
                前进();
            }
        }
        期望(标记类型::大于, "类型参数后应有'>'");
    }

    // 解析输入参数 (在函数名之前) - ()可省略
    if (_当前标记.类型 == 标记类型::左括号) {
        前进();
        if (_当前标记.类型 == 标记类型::右括号) {
            // 空参数列表
        } else {
            参数列表 = 解析参数列表("", true, true);
        }
        期望(标记类型::右括号, "函数参数后应有')'");
    }

    // 解析函数名
    std::string 函数名 = _当前标记.值;
    前进();

    // 解析返回值声明 (在函数名之后) - ()可省略，空可省略
    std::vector<返回值描述> 返回值列表;
    返回值列表 = 解析返回值列表();

    auto 主体 = 解析代码块();
    return std::make_unique<函数>(函数名, std::move(类型参数列表), std::move(参数列表), std::move(返回值列表),
                                 std::move(主体));
}

std::unique_ptr<程序> 语法分析器::解析程序() {
    auto 程序 = std::make_unique<struct 程序>();
    while (_当前标记.类型 != 标记类型::文件结束) {
        if (_当前标记.类型 == 标记类型::整数 || _当前标记.类型 == 标记类型::浮点 ||
                   _当前标记.类型 == 标记类型::字符串 || _当前标记.类型 == 标记类型::真 ||
                   _当前标记.类型 == 标记类型::假) {
            // 新语法：值 = 变量 名; 或 值 = 名;
            auto 初始值 = 解析表达式();
            if (_当前标记.类型 == 标记类型::等于) {
                前进();
                std::string 变量名;
                if (_当前标记.类型 == 标记类型::变量) {
                    // 值 = 变量 名 形式
                    前进();
                    期望类型(标记类型::标识符, "变量后应有标识符（变量名）");
                    变量名 = _当前标记.值;
                    前进();
                } else if (_当前标记.类型 == 标记类型::标识符) {
                    // 值 = 名 形式
                    变量名 = _当前标记.值;
                    前进();
                } else {
                    throw std::runtime_error("赋值目标应为标识符或'变量'关键字");
                }
                if (_当前标记.类型 == 标记类型::冒号) {
                    前进();
                    if (_当前标记.类型 == 标记类型::整数类型 || _当前标记.类型 == 标记类型::布尔类型 ||
                        _当前标记.类型 == 标记类型::浮点类型 || _当前标记.类型 == 标记类型::标识符) {
                        前进();
                    }
                }
                期望(标记类型::分号, "变量声明后应有';'");
                auto 声明 = std::make_unique<全局变量声明>();
                声明->变量名 = 变量名;
                声明->初始值 = std::move(初始值);
                程序->全局变量.push_back(std::move(声明));
            } else {
                throw std::runtime_error("全局作用域中表达式后应有'='");
            }
        } else if (_当前标记.类型 == 标记类型::结构体) {
            // 全局结构体定义
            前进();
            期望类型(标记类型::标识符, "结构体名应为标识符");
            std::string 名称 = _当前标记.值;
            前进();
            期望(标记类型::左花括号, "结构体后应有'{'");
            std::vector<结构体成员> 成员列表;
            std::vector<结构体方法> 方法列表;
            while (_当前标记.类型 != 标记类型::右花括号 && _当前标记.类型 != 标记类型::文件结束) {
                if (_当前标记.类型 == 标记类型::方法) {
                    // 解析方法
                    前进();
                    期望类型(标记类型::标识符, "方法名应为标识符");
                    std::string 方法名 = _当前标记.值;
                    前进();
                    期望(标记类型::左括号, "方法名后应有'('");
                    std::vector<函数参数> 参数列表;
                    if (_当前标记.类型 != 标记类型::右括号) {
                        参数列表 = 解析参数列表();
                    }
                    期望(标记类型::右括号, "方法参数后应有')'");
                    auto 返回值列表 = 解析返回值列表();
                    auto 主体 = 解析代码块();
                    方法列表.push_back({方法名, std::move(参数列表), std::move(返回值列表), std::move(主体)});
                } else {
                    // 解析成员
                    期望类型(标记类型::标识符, "成员名应为标识符");
                    std::string 成员名 = _当前标记.值;
                    前进();
                    期望(标记类型::冒号, "成员名后应有':'");
                    std::string 类型名 = _当前标记.值;
                    if (_当前标记.类型 == 标记类型::整数类型 || _当前标记.类型 == 标记类型::浮点类型 ||
                        _当前标记.类型 == 标记类型::布尔类型 || _当前标记.类型 == 标记类型::标识符) {
                        前进();
                    } else {
                        期望类型(标记类型::标识符, "成员类型应为类型名");
                    }
                    期望(标记类型::分号, "成员声明后应有';'");
                    成员列表.push_back({成员名, 类型名});
                }
            }
            期望(标记类型::右花括号, "结构体定义应以'}'结束");
            // 将方法转换为普通函数并添加到程序
            for (auto& 方法 : 方法列表) {
                std::vector<函数参数> 参数;
                参数.push_back({名称, 名称, nullptr});  // 自动添加结构体参数
                for (auto& p : 方法.参数列表) {
                    参数.push_back(std::move(p));
                }
                auto 函数_ptr = std::make_unique<函数>(名称 + "_" + 方法.名称, std::vector<std::string>{},
                    std::move(参数), std::move(方法.返回值列表), std::move(方法.主体));
                程序->函数列表.push_back(std::move(函数_ptr));
            }
            程序->结构体定义列表.push_back({名称, std::move(成员列表)});
        } else if (_当前标记.类型 == 标记类型::导入) {
            前进();
            期望类型(标记类型::字符串, "导入后应为文件路径字符串");
            std::string 模块名 = _当前标记.值;
            前进();
            
            // 检查是否有别名 (导入 "模块" as 别名)
            std::string 别名;
            if (_当前标记.类型 == 标记类型::标识符 && _当前标记.值 == "as") {
                前进();
                期望类型(标记类型::标识符, "别名应为标识符");
                别名 = _当前标记.值;
                前进();
            }
            
            // 检查是否有选择性导入 (导入 "模块" { 函数1, 函数2 })
            std::vector<std::string> 选择导入列表;
            if (_当前标记.类型 == 标记类型::左花括号) {
                前进();
                if (_当前标记.类型 == 标记类型::标识符) {
                    选择导入列表.push_back(_当前标记.值);
                    前进();
                    while (_当前标记.类型 == 标记类型::逗号) {
                        前进();
                        期望类型(标记类型::标识符, "导入函数名应为标识符");
                        选择导入列表.push_back(_当前标记.值);
                        前进();
                    }
                }
                期望(标记类型::右花括号, "选择性导入后应有'}'");
            }
            
            期望(标记类型::分号, "导入后应有';'");
            导入列表.push_back(模块名);
            if (!别名.empty()) {
                导入别名映射[模块名] = 别名;
            }
            if (!选择导入列表.empty()) {
                选择导入映射[模块名] = 选择导入列表;
            }
        } else if (_当前标记.类型 == 标记类型::枚举) {
            // 全局枚举定义
            前进();
            期望类型(标记类型::标识符, "枚举名应为标识符");
            std::string 名称 = _当前标记.值;
            前进();
            期望(标记类型::左花括号, "枚举后应有'{'");
            std::vector<枚举成员> 成员列表;
            int 当前值 = 0;
            while (_当前标记.类型 != 标记类型::右花括号 && _当前标记.类型 != 标记类型::文件结束) {
                期望类型(标记类型::标识符, "枚举成员名应为标识符");
                std::string 成员名 = _当前标记.值;
                前进();
                if (_当前标记.类型 == 标记类型::等于) {
                    // 显式值: 红=1
                    前进();
                    期望类型(标记类型::整数, "枚举值应为整数");
                    当前值 = std::stoi(_当前标记.值);
                    前进();
                }
                成员列表.push_back({成员名, 当前值});
                当前值++;
                if (_当前标记.类型 == 标记类型::逗号) 前进();
            }
            期望(标记类型::右花括号, "枚举定义应以'}'结束");
            程序->枚举定义列表.push_back({名称, std::move(成员列表)});
        } else if (_当前标记.类型 == 标记类型::类型 ||
                   (_当前标记.类型 == 标记类型::整数类型 || _当前标记.类型 == 标记类型::浮点类型 ||
                    _当前标记.类型 == 标记类型::布尔类型 || _当前标记.类型 == 标记类型::字符串类型 ||
                    _当前标记.类型 == 标记类型::标识符)) {
            // 类型别名: 原始类型 = 别名:类型
            // 支持: 类型 整数 = 别名:类型; 或 整数 = 别名:类型;
            
            // 读取原始类型
            std::string 原始类型;
            if (_当前标记.类型 == 标记类型::类型) {
                前进();  // 跳过可选的 类型 关键字
            }
            if (_当前标记.类型 == 标记类型::整数类型 || _当前标记.类型 == 标记类型::浮点类型 ||
                _当前标记.类型 == 标记类型::布尔类型 || _当前标记.类型 == 标记类型::字符串类型 ||
                _当前标记.类型 == 标记类型::标识符) {
                原始类型 = _当前标记.值;
                前进();
                // 检查泛型参数 <T>
                if (_当前标记.类型 == 标记类型::小于) {
                    原始类型 += "<";
                    前进();
                    if (_当前标记.类型 == 标记类型::标识符) {
                        原始类型 += _当前标记.值;
                        前进();
                    }
                    期望(标记类型::大于, "泛型参数后应有'>'");
                    原始类型 += ">";
                }
                // 检查数组后缀 []
                if (_当前标记.类型 == 标记类型::左方括号) {
                    原始类型 += "[]";
                    前进();
                    期望(标记类型::右方括号, "数组类型应有']'");
                }
            }
            // 检查是否为类型别名（需要 = 和 :类型）
            if (_当前标记.类型 == 标记类型::等于) {
                // 保存位置用于回溯
                size_t 保存位置 = _词法分析器.获取位置();
                int 保存行号 = _词法分析器.获取当前行();
                标记 保存标记 = _当前标记;
                
                前进();  // 跳过 =
                // 读取别名
                std::string 别名;
                if (_当前标记.类型 == 标记类型::标识符 || _当前标记.类型 == 标记类型::整数类型 ||
                    _当前标记.类型 == 标记类型::浮点类型 || _当前标记.类型 == 标记类型::布尔类型 ||
                    _当前标记.类型 == 标记类型::字符串类型) {
                    别名 = _当前标记.值;
                    前进();
                    // 检查是否有 :类型
                    if (_当前标记.类型 == 标记类型::冒号) {
                        前进();
                        if (_当前标记.类型 == 标记类型::类型) {
                            // 确认是类型别名
                            前进();
                            期望(标记类型::分号, "类型别名后应有';'");
                            程序->类型别名列表.push_back({别名, 原始类型});
                        } else {
                            // 不是类型别名，回溯
                            _词法分析器.设置位置(保存位置);
                            _词法分析器.设置当前行(保存行号);
                            _当前标记 = 保存标记;
                            // 解析为普通语句
                            程序->函数列表.push_back(解析函数());
                        }
                    } else {
                        // 不是类型别名，回溯
                        _词法分析器.设置位置(保存位置);
                        _词法分析器.设置当前行(保存行号);
                        _当前标记 = 保存标记;
                        // 解析为普通语句
                        程序->函数列表.push_back(解析函数());
                    }
                } else {
                    // 不是类型别名，回溯
                    _词法分析器.设置位置(保存位置);
                    _词法分析器.设置当前行(保存行号);
                    _当前标记 = 保存标记;
                    // 解析为普通语句
                    程序->函数列表.push_back(解析函数());
                }
            } else {
                // 不是类型别名，回溯并解析为普通语句
                // 需要回退到原始类型之前
                程序->函数列表.push_back(解析函数());
            }
        } else {
            程序->函数列表.push_back(解析函数());
        }
    }
    return 程序;
}
