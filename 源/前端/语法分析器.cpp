#include "语法分析器.h"
#include <stdexcept>

void 语法分析器::前进() {
    _当前标记 = _词法分析器.下一个标记();
    调试打印("[语法分析器][前进] 新标记: " << 标记类型转字符串(_当前标记.类型) << " ('" << _当前标记.值 << "')");
}

void 语法分析器::期望类型(标记类型 类型, const std::string& 信息) {
    if (_当前标记.类型 != 类型) {
        throw std::runtime_error(信息 + "（行 " + std::to_string(_当前标记.行号) + "，得到 '" + _当前标记.值 + "'）");
    }
}

void 语法分析器::期望(标记类型 类型, const std::string& 信息) {
    期望类型(类型, 信息);
    前进();
}

std::unique_ptr<表达式> 语法分析器::解析基本表达式() {
    标记 当前 = _当前标记;

    if (当前.类型 == 标记类型::整数) {
        前进();
        return std::make_unique<整数表达式>(std::stoi(当前.值));
    }

    if (当前.类型 == 标记类型::浮点) {
        前进();
        return std::make_unique<浮点表达式>(std::stod(当前.值));
    }

    if (当前.类型 == 标记类型::真) {
        前进();
        return std::make_unique<布尔表达式>(true);
    }

    if (当前.类型 == 标记类型::假) {
        前进();
        return std::make_unique<布尔表达式>(false);
    }

    if (当前.类型 == 标记类型::字符) {
        int 字符值 = std::stoi(当前.值);
        前进();
        return std::make_unique<字符表达式>(字符值);
    }

    if (当前.类型 == 标记类型::字符串) {
        前进();
        return std::make_unique<字符串表达式>(当前.值);
    }

    if (当前.类型 == 标记类型::字符串插值) {
        前进();
        // 解析字符串插值: 将内容按 { 和 } 分割为文本部分和表达式部分
        std::string 原始内容 = 当前.值;
        // 恢复转义的 \x01 为 {
        for (char& c : 原始内容) { if (c == '\x01') c = '{'; }
        
        struct 插值片段 { bool 是文本; std::string 内容; };
        std::vector<插值片段> 片段列表;
        std::string 当前文本;
        size_t pos = 0;
        while (pos < 原始内容.size()) {
            if (原始内容[pos] == '{') {
                if (!当前文本.empty()) {
                    片段列表.push_back({true, 当前文本});
                    当前文本.clear();
                }
                // 找到匹配的 '}'
                int 深度 = 1;
                size_t expr开始 = pos + 1;
                size_t expr结束 = expr开始;
                while (expr结束 < 原始内容.size() && 深度 > 0) {
                    if (原始内容[expr结束] == '{') 深度++;
                    else if (原始内容[expr结束] == '}') 深度--;
                    if (深度 > 0) expr结束++;
                }
                if (深度 == 0) {
                    片段列表.push_back({false, 原始内容.substr(expr开始, expr结束 - expr开始)});
                    pos = expr结束 + 1;
                } else {
                    当前文本 += '{';
                    pos = expr开始;
                }
            } else {
                当前文本 += 原始内容[pos];
                pos++;
            }
        }
        if (!当前文本.empty()) {
            片段列表.push_back({true, 当前文本});
        }
        
        if (片段列表.empty()) {
            return std::make_unique<字符串表达式>("");
        }
        
        // 将片段转换为表达式并拼接
        auto 创建表达式 = [&](const 插值片段& 片段) -> std::unique_ptr<表达式> {
            if (片段.是文本) {
                return std::make_unique<字符串表达式>(片段.内容);
            } else {
                语法分析器 子分析器(片段.内容.c_str(), 片段.内容.size());
                auto 子表达式 = 子分析器.解析表达式();
                // 将非字符串表达式包装为 转字符串() 调用
                if (子表达式->类型 != 表达式类型::字符串) {
                    std::vector<std::unique_ptr<表达式>> 参数列表;
                    参数列表.push_back(std::move(子表达式));
                    return std::make_unique<函数调用表达式>("转字符串", std::move(参数列表));
                }
                return 子表达式;
            }
        };
        
        auto 结果 = 创建表达式(片段列表[0]);
        for (size_t i = 1; i < 片段列表.size(); i++) {
            auto 右 = 创建表达式(片段列表[i]);
            结果 = std::make_unique<二元运算表达式>(二元操作符::加法, std::move(结果), std::move(右));
        }
        return 结果;
    }

    if (当前.类型 == 标记类型::标识符) {
        std::string 名称 = 当前.值;
        前进();
        if (_当前标记.类型 == 标记类型::左括号) {
            // 函数调用
            前进();
            std::vector<std::unique_ptr<表达式>> 参数;
            if (_当前标记.类型 != 标记类型::右括号) {
                参数.push_back(解析表达式());
                while (_当前标记.类型 == 标记类型::逗号) {
                    前进();
                    参数.push_back(解析表达式());
                }
            }
            期望(标记类型::右括号, "函数调用后应有')'");
            return std::make_unique<函数调用表达式>(名称, std::move(参数));
        }
        if (_当前标记.类型 == 标记类型::左方括号) {
            前进();
            // 检查是否为分片 arr[1:3] 或 arr[:] 或 arr[1:]
            if (_当前标记.类型 == 标记类型::冒号) {
                // arr[:] 或 arr[:end]
                前进();
                std::unique_ptr<表达式> 结束索引;
                if (_当前标记.类型 != 标记类型::右方括号) {
                    结束索引 = 解析表达式();
                }
                期望(标记类型::右方括号, "分片后应有']'");
                return std::make_unique<分片访问表达式>(名称, nullptr, std::move(结束索引));
            }
            auto 索引 = 解析表达式();
            if (_当前标记.类型 == 标记类型::冒号) {
                // arr[start:end] 或 arr[start:]
                前进();
                std::unique_ptr<表达式> 结束索引;
                if (_当前标记.类型 != 标记类型::右方括号) {
                    结束索引 = 解析表达式();
                }
                期望(标记类型::右方括号, "分片后应有']'");
                return std::make_unique<分片访问表达式>(名称, std::move(索引), std::move(结束索引));
            }
            期望(标记类型::右方括号, "下标后应有']'");
            return std::make_unique<下标访问表达式>(名称, std::move(索引));
        }
        if (_当前标记.类型 == 标记类型::句号) {
            // 成员访问: 对象.成员 或 元组访问: 元组.数字
            前进();
            if (_当前标记.类型 == 标记类型::整数) {
                // 元组访问
                int 索引 = std::stoi(_当前标记.值);
                前进();
                return std::make_unique<元组访问表达式>(名称, 索引);
            }
            期望类型(标记类型::标识符, "成员名应为标识符");
            std::string 成员名 = _当前标记.值;
            前进();
            return std::make_unique<成员访问表达式>(名称, 成员名);
        }
        if (_当前标记.类型 == 标记类型::冒号) {
            // 检查是否为枚举成员访问: 枚举名::成员名
            前进();
            if (_当前标记.类型 == 标记类型::冒号) {
                前进();
                期望类型(标记类型::标识符, "枚举成员名应为标识符");
                std::string 成员名 = _当前标记.值;
                前进();
                return std::make_unique<枚举成员表达式>(名称, 成员名);
            }
            // 不是::，回溯（这种情况不应该发生，但为了安全）
            throw std::runtime_error("意外的':'（行 " + std::to_string(_当前标记.行号) + "）");
        }
        if (_当前标记.类型 == 标记类型::左花括号) {
            // 结构体实例: 名称 { 成员赋值列表 }
            前进();
            std::vector<std::pair<std::string, std::unique_ptr<表达式>>> 成员列表;
            while (_当前标记.类型 != 标记类型::右花括号 && _当前标记.类型 != 标记类型::文件结束) {
                期望类型(标记类型::标识符, "成员名应为标识符");
                std::string 成员名 = _当前标记.值;
                前进();
                期望(标记类型::冒号, "成员名后应有':'");
                auto 值 = 解析表达式();
                成员列表.push_back({成员名, std::move(值)});
                if (_当前标记.类型 == 标记类型::逗号) 前进();
            }
            期望(标记类型::右花括号, "结构体实例应以'}'结束");
            return std::make_unique<结构体实例表达式>(名称, std::move(成员列表));
        }
        // 自增自减: 变量+| 或 变量-|
        if (_当前标记.类型 == 标记类型::自增) {
            前进();
            return std::make_unique<自增自减表达式>(名称, true);
        }
        if (_当前标记.类型 == 标记类型::自减) {
            前进();
            return std::make_unique<自增自减表达式>(名称, false);
        }
        return std::make_unique<变量表达式>(名称);
    }

    if (当前.类型 == 标记类型::左方括号) {
        前进();
        // 检查是否为映射字面量 ["键": 值, ...]
        // 通过前瞻判断：如果第一个元素后跟':'，则是映射
        if (_当前标记.类型 == 标记类型::字符串) {
            // 保存当前状态以支持回溯
            std::string 第一个键 = _当前标记.值;
            前进();
            if (_当前标记.类型 == 标记类型::冒号) {
                // 是映射字面量
                前进();
                auto 第一个值 = 解析表达式();
                std::vector<std::pair<std::unique_ptr<表达式>, std::unique_ptr<表达式>>> 键值对;
                键值对.push_back({std::make_unique<字符串表达式>(第一个键), std::move(第一个值)});
                while (_当前标记.类型 == 标记类型::逗号) {
                    前进();
                    期望类型(标记类型::字符串, "映射键应为字符串");
                    std::string 键 = _当前标记.值;
                    前进();
                    期望(标记类型::冒号, "映射键后应有':'");
                    auto 值 = 解析表达式();
                    键值对.push_back({std::make_unique<字符串表达式>(键), std::move(值)});
                }
                期望(标记类型::右方括号, "映射字面量应有']'闭合");
                return std::make_unique<映射字面量表达式>(std::move(键值对));
            }
            // 不是映射，回溯：将字符串作为数组元素
            auto 第一个元素 = std::make_unique<字符串表达式>(第一个键);
            std::vector<std::unique_ptr<表达式>> 元素;
            元素.push_back(std::move(第一个元素));
            while (_当前标记.类型 == 标记类型::逗号) {
                前进();
                元素.push_back(解析表达式());
            }
            期望(标记类型::右方括号, "数组字面量应有']'闭合");
            return std::make_unique<数组字面量表达式>(std::move(元素));
        }
        // 数组字面量
        std::vector<std::unique_ptr<表达式>> 元素;
        if (_当前标记.类型 != 标记类型::右方括号) {
            元素.push_back(解析表达式());
            while (_当前标记.类型 == 标记类型::逗号) {
                前进();
                元素.push_back(解析表达式());
            }
        }
        期望(标记类型::右方括号, "数组字面量应有']'闭合");
        return std::make_unique<数组字面量表达式>(std::move(元素));
    }

    if (当前.类型 == 标记类型::函数) {
        前进();
        期望(标记类型::左括号, "匿名函数后应有'('");
        std::vector<函数参数> 参数列表;
        if (_当前标记.类型 == 标记类型::标识符) {
            std::string 参数名 = _当前标记.值;
            std::string 参数类型;
            前进();
            if (_当前标记.类型 == 标记类型::冒号) {
                前进();
                参数类型 = _当前标记.值;
                if (_当前标记.类型 == 标记类型::整数类型 || _当前标记.类型 == 标记类型::浮点类型 ||
                    _当前标记.类型 == 标记类型::布尔类型 || _当前标记.类型 == 标记类型::标识符) {
                    前进();
                } else {
                    期望类型(标记类型::标识符, "参数类型应为类型名");
                }
            }
            参数列表.push_back({参数名, 参数类型});
            while (_当前标记.类型 == 标记类型::逗号) {
                前进();
                期望类型(标记类型::标识符, "参数名应为标识符");
                参数名 = _当前标记.值;
                参数类型.clear();
                前进();
                if (_当前标记.类型 == 标记类型::冒号) {
                    前进();
                    参数类型 = _当前标记.值;
                    if (_当前标记.类型 == 标记类型::整数类型 || _当前标记.类型 == 标记类型::浮点类型 ||
                        _当前标记.类型 == 标记类型::布尔类型 || _当前标记.类型 == 标记类型::标识符) {
                        前进();
                    } else {
                        期望类型(标记类型::标识符, "参数类型应为类型名");
                    }
                }
                参数列表.push_back({参数名, 参数类型});
            }
        }
        期望(标记类型::右括号, "匿名函数参数后应有')'");
        std::string 返回类型;
        if (_当前标记.类型 == 标记类型::冒号) {
            前进();
            返回类型 = _当前标记.值;
            if (_当前标记.类型 == 标记类型::整数类型 || _当前标记.类型 == 标记类型::浮点类型 ||
                _当前标记.类型 == 标记类型::布尔类型 || _当前标记.类型 == 标记类型::字符串类型 ||
                _当前标记.类型 == 标记类型::标识符) {
                前进();
            } else if (_当前标记.类型 == 标记类型::空) {
                前进();
            } else {
                throw std::runtime_error("应有返回类型");
            }
        }
        auto 主体 = 解析代码块();
        return std::make_unique<匿名函数表达式>(std::move(参数列表), 返回类型, std::move(主体));
    }

    if (当前.类型 == 标记类型::左括号) {
        前进();
        auto 第一个表达式 = 解析表达式();
        // 检查是否为元组字面量 (expr, expr, ...)
        if (_当前标记.类型 == 标记类型::逗号) {
            std::vector<std::unique_ptr<表达式>> 元素列表;
            元素列表.push_back(std::move(第一个表达式));
            while (_当前标记.类型 == 标记类型::逗号) {
                前进();
                元素列表.push_back(解析表达式());
            }
            期望(标记类型::右括号, "元组后应有')'");
            return std::make_unique<元组字面量表达式>(std::move(元素列表));
        }
        期望(标记类型::右括号, "表达式后应有')'");
        return 第一个表达式;
    }

    throw std::runtime_error("表达式中意外标记 '" + 当前.值 + "'（行 " + std::to_string(当前.行号) + "）");
}

std::unique_ptr<表达式> 语法分析器::解析一元表达式() {
    if (_当前标记.类型 == 标记类型::感叹号) {
        前进();
        auto 操作数 = 解析一元表达式();
        return std::make_unique<一元运算表达式>(一元操作符::逻辑非, std::move(操作数));
    }
    if (_当前标记.类型 == 标记类型::减号) {
        前进();
        auto 操作数 = 解析一元表达式();
        return std::make_unique<一元运算表达式>(一元操作符::取负, std::move(操作数));
    }
    return 解析基本表达式();
}

std::unique_ptr<表达式> 语法分析器::解析乘除表达式() {
    auto 左 = 解析一元表达式();
    while (_当前标记.类型 == 标记类型::乘号 || _当前标记.类型 == 标记类型::除号 || _当前标记.类型 == 标记类型::百分号) {
        二元操作符 op = (_当前标记.类型 == 标记类型::乘号) ? 二元操作符::乘法 :
                         (_当前标记.类型 == 标记类型::除号) ? 二元操作符::除法 : 二元操作符::取模;
        前进();
        auto 右 = 解析一元表达式();
        左 = std::make_unique<二元运算表达式>(op, std::move(左), std::move(右));
    }
    return 左;
}

std::unique_ptr<表达式> 语法分析器::解析加减表达式() {
    auto 左 = 解析乘除表达式();
    while (_当前标记.类型 == 标记类型::加号 || _当前标记.类型 == 标记类型::减号) {
        二元操作符 op = (_当前标记.类型 == 标记类型::加号) ? 二元操作符::加法 : 二元操作符::减法;
        前进();
        auto 右 = 解析乘除表达式();
        左 = std::make_unique<二元运算表达式>(op, std::move(左), std::move(右));
    }
    return 左;
}

std::unique_ptr<表达式> 语法分析器::解析移位表达式() {
    auto 左 = 解析加减表达式();
    while (_当前标记.类型 == 标记类型::左移 || _当前标记.类型 == 标记类型::右移) {
        二元操作符 op = (_当前标记.类型 == 标记类型::左移) ? 二元操作符::左移 : 二元操作符::右移;
        前进();
        auto 右 = 解析加减表达式();
        左 = std::make_unique<二元运算表达式>(op, std::move(左), std::move(右));
    }
    return 左;
}

std::unique_ptr<表达式> 语法分析器::解析比较表达式() {
    auto 左 = 解析移位表达式();
    while (_当前标记.类型 == 标记类型::等于等于 || _当前标记.类型 == 标记类型::感叹号等于 ||
           _当前标记.类型 == 标记类型::小于 || _当前标记.类型 == 标记类型::大于 ||
           _当前标记.类型 == 标记类型::小于等于 || _当前标记.类型 == 标记类型::大于等于) {
        二元操作符 op;
        switch (_当前标记.类型) {
            case 标记类型::等于等于: op = 二元操作符::等于; break;
            case 标记类型::感叹号等于: op = 二元操作符::不等于; break;
            case 标记类型::小于: op = 二元操作符::小于; break;
            case 标记类型::大于: op = 二元操作符::大于; break;
            case 标记类型::小于等于: op = 二元操作符::小于等于; break;
            case 标记类型::大于等于: op = 二元操作符::大于等于; break;
            default: throw std::runtime_error("未知比较运算符");
        }
        前进();
        auto 右 = 解析加减表达式();
        左 = std::make_unique<二元运算表达式>(op, std::move(左), std::move(右));
    }
    return 左;
}

std::unique_ptr<表达式> 语法分析器::解析位与表达式() {
    auto 左 = 解析比较表达式();
    while (_当前标记.类型 == 标记类型::位与) {
        前进();
        auto 右 = 解析比较表达式();
        左 = std::make_unique<二元运算表达式>(二元操作符::位与, std::move(左), std::move(右));
    }
    return 左;
}

std::unique_ptr<表达式> 语法分析器::解析位异或表达式() {
    auto 左 = 解析位与表达式();
    while (_当前标记.类型 == 标记类型::位异或) {
        前进();
        auto 右 = 解析位与表达式();
        左 = std::make_unique<二元运算表达式>(二元操作符::位异或, std::move(左), std::move(右));
    }
    return 左;
}

std::unique_ptr<表达式> 语法分析器::解析位或表达式() {
    auto 左 = 解析位异或表达式();
    while (_当前标记.类型 == 标记类型::位或) {
        前进();
        auto 右 = 解析位异或表达式();
        左 = std::make_unique<二元运算表达式>(二元操作符::位或, std::move(左), std::move(右));
    }
    return 左;
}

std::unique_ptr<表达式> 语法分析器::解析逻辑与表达式() {
    auto 左 = 解析位或表达式();
    while (_当前标记.类型 == 标记类型::与与) {
        前进();
        auto 右 = 解析比较表达式();
        左 = std::make_unique<二元运算表达式>(二元操作符::逻辑与, std::move(左), std::move(右));
    }
    return 左;
}

std::unique_ptr<表达式> 语法分析器::解析逻辑或表达式() {
    auto 左 = 解析逻辑与表达式();
    while (_当前标记.类型 == 标记类型::或或) {
        前进();
        auto 右 = 解析逻辑与表达式();
        左 = std::make_unique<二元运算表达式>(二元操作符::逻辑或, std::move(左), std::move(右));
    }
    return 左;
}

std::unique_ptr<表达式> 语法分析器::解析表达式() {
    return 解析逻辑或表达式();
}

std::vector<std::unique_ptr<语句>> 语法分析器::解析代码块() {
    期望(标记类型::左花括号, "应有'{'");
    std::vector<std::unique_ptr<语句>> 语句列表;
    while (_当前标记.类型 != 标记类型::右花括号 && _当前标记.类型 != 标记类型::文件结束) {
        语句列表.push_back(解析语句());
    }
    期望(标记类型::右花括号, "应有'}'闭合");
    return 语句列表;
}

std::unique_ptr<语句> 语法分析器::解析语句() {
    标记 当前 = _当前标记;

    if (当前.类型 == 标记类型::变量 || 当前.类型 == 标记类型::常量) {
        bool 是常量 = (当前.类型 == 标记类型::常量);
        前进();
        期望类型(标记类型::标识符, (是常量 ? "常量" : "变量") + std::string("后应有标识符"));
        std::string 变量名 = _当前标记.值;
        前进();
        if (_当前标记.类型 == 标记类型::冒号) {
            前进();
            if (_当前标记.类型 == 标记类型::整数类型 || _当前标记.类型 == 标记类型::浮点类型 ||
                _当前标记.类型 == 标记类型::布尔类型 || _当前标记.类型 == 标记类型::标识符) {
                前进();
            } else {
                期望类型(标记类型::标识符, "类型注解应为类型名");
            }
        }
        期望(标记类型::等于, (是常量 ? "常量名" : "变量名") + std::string("后应有'='"));
        auto 初始值 = 解析表达式();
        期望(标记类型::分号, (是常量 ? "常量" : "变量") + std::string("初始化后应有';'"));
        if (是常量) {
            return std::make_unique<常量声明>(变量名, std::move(初始值));
        }
        return std::make_unique<变量声明>(变量名, std::move(初始值));
    }

    if (当前.类型 == 标记类型::标识符) {
        std::string 变量名 = 当前.值;
        前进();
        if (_当前标记.类型 == 标记类型::左方括号) {
            前进();
            auto 索引 = 解析表达式();
            期望(标记类型::右方括号, "下标后应有']'");
            期望(标记类型::等于, "下标后应有'='");
            auto 值 = 解析表达式();
            期望(标记类型::分号, "赋值后应有';'");
            return std::make_unique<下标赋值语句>(变量名, std::move(索引), std::move(值));
        }
        if (_当前标记.类型 == 标记类型::句号) {
            // 成员赋值: 对象.成员 = 值
            前进();
            期望类型(标记类型::标识符, "成员名应为标识符");
            std::string 成员名 = _当前标记.值;
            前进();
            期望(标记类型::等于, "成员后应有'='");
            auto 值 = 解析表达式();
            期望(标记类型::分号, "赋值后应有';'");
            // 将成员赋值转换为：对象[成员索引] = 值 (由代码生成器处理)
            return std::make_unique<赋值语句>(变量名 + "." + 成员名, std::move(值));
        }
        if (_当前标记.类型 == 标记类型::等于) {
            前进();
            auto 值 = 解析表达式();
            期望(标记类型::分号, "赋值后应有';'");
            return std::make_unique<赋值语句>(变量名, std::move(值));
        }
        if (_当前标记.类型 == 标记类型::加等于 || _当前标记.类型 == 标记类型::减等于 ||
            _当前标记.类型 == 标记类型::乘等于 || _当前标记.类型 == 标记类型::除等于 ||
            _当前标记.类型 == 标记类型::模等于 || _当前标记.类型 == 标记类型::位与等于 ||
            _当前标记.类型 == 标记类型::位或等于 || _当前标记.类型 == 标记类型::位异或等于 ||
            _当前标记.类型 == 标记类型::左移等于 || _当前标记.类型 == 标记类型::右移等于) {
            二元操作符 op;
            switch (_当前标记.类型) {
                case 标记类型::加等于: op = 二元操作符::加法; break;
                case 标记类型::减等于: op = 二元操作符::减法; break;
                case 标记类型::乘等于: op = 二元操作符::乘法; break;
                case 标记类型::除等于: op = 二元操作符::除法; break;
                case 标记类型::模等于: op = 二元操作符::取模; break;
                case 标记类型::位与等于: op = 二元操作符::位与; break;
                case 标记类型::位或等于: op = 二元操作符::位或; break;
                case 标记类型::位异或等于: op = 二元操作符::位异或; break;
                case 标记类型::左移等于: op = 二元操作符::左移; break;
                case 标记类型::右移等于: op = 二元操作符::右移; break;
                default: throw std::runtime_error("未知复合赋值");
            }
            前进();
            auto 右值 = 解析表达式();
            auto 变量引用 = std::make_unique<变量表达式>(变量名);
            auto 二元 = std::make_unique<二元运算表达式>(op, std::move(变量引用), std::move(右值));
            期望(标记类型::分号, "赋值后应有';'");
            return std::make_unique<赋值语句>(变量名, std::move(二元));
        }
        if (_当前标记.类型 == 标记类型::左括号) {
            前进();
            std::vector<std::unique_ptr<表达式>> 参数;
            if (_当前标记.类型 != 标记类型::右括号) {
                参数.push_back(解析表达式());
                while (_当前标记.类型 == 标记类型::逗号) {
                    前进();
                    参数.push_back(解析表达式());
                }
            }
            期望(标记类型::右括号, "函数调用后应有')'");
            期望(标记类型::分号, "函数调用后应有';'");
            auto 调用 = std::make_unique<函数调用表达式>(变量名, std::move(参数));
            return std::make_unique<表达式语句>(std::move(调用));
        }
        // 自增自减语句: 变量+| 或 变量-|
        if (_当前标记.类型 == 标记类型::自增 || _当前标记.类型 == 标记类型::自减) {
            bool 是自增 = (_当前标记.类型 == 标记类型::自增);
            前进();
            期望(标记类型::分号, "自增自减后应有';'");
            auto 表达式 = std::make_unique<自增自减表达式>(变量名, 是自增);
            return std::make_unique<表达式语句>(std::move(表达式));
        }
        throw std::runtime_error("标识符 '" + 变量名 + "' 后应有 '=' 或 '('（行 " + std::to_string(当前.行号) + "）");
    }

    if (当前.类型 == 标记类型::如果) {
        前进();
        期望(标记类型::左括号, "如果后应有'('");
        auto 条件 = 解析表达式();
        期望(标记类型::右括号, "如果条件后应有')'");
        auto then块 = 解析代码块();

        std::vector<否则如果分支> 否则如果列表;
        while (_当前标记.类型 == 标记类型::否则如果) {
            前进();
            期望(标记类型::左括号, "否则如果后应有'('");
            auto elif条件 = 解析表达式();
            期望(标记类型::右括号, "否则如果条件后应有')'");
            auto elif主体 = 解析代码块();
            否则如果分支 分支;
            分支.条件 = std::move(elif条件);
            分支.主体 = std::move(elif主体);
            否则如果列表.push_back(std::move(分支));
        }

        std::vector<std::unique_ptr<语句>> else块;
        if (_当前标记.类型 == 标记类型::否则) {
            前进();
            else块 = 解析代码块();
        }
        return std::make_unique<如果语句>(std::move(条件), std::move(then块), std::move(否则如果列表), std::move(else块));
    }

    if (当前.类型 == 标记类型::循环) {
        前进();
        if (_当前标记.类型 == 标记类型::左括号) {
            // for循环: 循环 (初始化; 条件; 步进) { ... }
            前进();
            std::unique_ptr<语句> 初始化;
            if (_当前标记.类型 != 标记类型::分号) {
                // 解析初始化语句
                if (_当前标记.类型 == 标记类型::变量) {
                    前进();
                    期望类型(标记类型::标识符, "变量后应有标识符");
                    std::string 变量名 = _当前标记.值;
                    前进();
                    期望(标记类型::等于, "变量名后应有'='");
                    auto 值 = 解析表达式();
                    初始化 = std::make_unique<变量声明>(变量名, std::move(值));
                } else {
                    // 普通表达式语句
                    auto expr = 解析表达式();
                    初始化 = std::make_unique<表达式语句>(std::move(expr));
                }
            }
            期望(标记类型::分号, "循环初始化后应有';'");
            std::unique_ptr<表达式> 条件;
            if (_当前标记.类型 != 标记类型::分号) {
                条件 = 解析表达式();
            }
            期望(标记类型::分号, "循环条件后应有';'");
            std::unique_ptr<语句> 步进;
            if (_当前标记.类型 != 标记类型::右括号) {
                // 解析步进语句（支持 +=, -=, *=, /=）
                期望类型(标记类型::标识符, "步进应以标识符开始");
                std::string 变量名 = _当前标记.值;
                前进();
                if (_当前标记.类型 == 标记类型::加等于 || _当前标记.类型 == 标记类型::减等于 ||
                    _当前标记.类型 == 标记类型::乘等于 || _当前标记.类型 == 标记类型::除等于) {
                    二元操作符 op;
                    switch (_当前标记.类型) {
                        case 标记类型::加等于: op = 二元操作符::加法; break;
                        case 标记类型::减等于: op = 二元操作符::减法; break;
                        case 标记类型::乘等于: op = 二元操作符::乘法; break;
                        case 标记类型::除等于: op = 二元操作符::除法; break;
                        default: throw std::runtime_error("未知复合赋值");
                    }
                    前进();
                    auto 右值 = 解析表达式();
                    auto 变量引用 = std::make_unique<变量表达式>(变量名);
                    auto 二元 = std::make_unique<二元运算表达式>(op, std::move(变量引用), std::move(右值));
                    步进 = std::make_unique<赋值语句>(变量名, std::move(二元));
                } else if (_当前标记.类型 == 标记类型::等于) {
                    前进();
                    auto 值 = 解析表达式();
                    步进 = std::make_unique<赋值语句>(变量名, std::move(值));
                } else {
                    // 普通表达式（如函数调用）
                    auto expr = 解析表达式();
                    步进 = std::make_unique<表达式语句>(std::move(expr));
                }
            }
            期望(标记类型::右括号, "循环步进后应有')'");
            auto 主体 = 解析代码块();
            return std::make_unique<循环语句>(std::move(初始化), std::move(条件), std::move(步进), std::move(主体));
        } else {
            // 无限循环: 循环 { ... }
            auto 主体 = 解析代码块();
            return std::make_unique<循环语句>(std::move(主体));
        }
    }

    if (当前.类型 == 标记类型::当) {
        前进();
        期望(标记类型::左括号, "当后应有'('");
        auto 条件 = 解析表达式();
        期望(标记类型::右括号, "当条件后应有')'");
        auto 主体 = 解析代码块();
        return std::make_unique<当循环语句>(std::move(条件), std::move(主体));
    }

    if (当前.类型 == 标记类型::做) {
        前进();
        auto 主体 = 解析代码块();
        if (_当前标记.类型 == 标记类型::当) {
            前进();
            期望(标记类型::左括号, "当后应有'('");
            auto 条件 = 解析表达式();
            期望(标记类型::右括号, "当条件后应有')'");
            期望(标记类型::分号, "做-当循环后应有';'");
            return std::make_unique<做循环语句>(std::move(条件), std::move(主体), true);
        }
        if (_当前标记.类型 == 标记类型::到) {
            前进();
            期望(标记类型::左括号, "到后应有'('");
            auto 条件 = 解析表达式();
            期望(标记类型::右括号, "到条件后应有')'");
            期望(标记类型::分号, "做-到循环后应有';'");
            return std::make_unique<做循环语句>(std::move(条件), std::move(主体), false);
        }
        throw std::runtime_error("做后应有'当'或'到'");
    }

    if (当前.类型 == 标记类型::中断) {
        前进();
        期望(标记类型::分号, "中断后应有';'");
        return std::make_unique<中断语句>();
    }

    if (当前.类型 == 标记类型::继续) {
        前进();
        期望(标记类型::分号, "继续后应有';'");
        return std::make_unique<继续语句>();
    }

    if (当前.类型 == 标记类型::返回) {
        前进();
        if (_当前标记.类型 == 标记类型::分号) {
            前进();
            return std::make_unique<返回语句>(nullptr);
        }
        auto 值 = 解析表达式();
        期望(标记类型::分号, "返回后应有';'");
        return std::make_unique<返回语句>(std::move(值));
    }

    if (当前.类型 == 标记类型::匹配) {
        前进();
        期望(标记类型::左括号, "匹配后应有'('");
        auto 表达式值 = 解析表达式();
        期望(标记类型::右括号, "匹配表达式后应有')'");
        期望(标记类型::左花括号, "匹配后应有'{'");

        std::vector<匹配分支> 分支列表;
        while (_当前标记.类型 != 标记类型::右花括号 && _当前标记.类型 != 标记类型::文件结束) {
            匹配分支 分支;
            if (_当前标记.类型 == 标记类型::标识符 && _当前标记.值 == "_") {
                // 默认分支
                前进();
            } else {
                分支.条件 = 解析表达式();
            }
            期望(标记类型::箭头, "匹配分支后应有'=>'");
            期望(标记类型::左花括号, "匹配分支体应以'{'开始");
            while (_当前标记.类型 != 标记类型::右花括号 && _当前标记.类型 != 标记类型::文件结束) {
                分支.主体.push_back(解析语句());
            }
            期望(标记类型::右花括号, "匹配分支体应以'}'结束");
            分支列表.push_back(std::move(分支));
        }
        期望(标记类型::右花括号, "匹配后应有'}'");
        return std::make_unique<匹配语句>(std::move(表达式值), std::move(分支列表));
    }

    if (当前.类型 == 标记类型::遍历) {
        前进();
        期望(标记类型::左括号, "遍历后应有'('");
        期望类型(标记类型::标识符, "遍历变量应为标识符");
        std::string 变量名 = _当前标记.值;
        前进();
        期望(标记类型::冒号, "遍历变量后应有':'");
        auto 数组表达式 = 解析表达式();
        期望(标记类型::右括号, "遍历后应有')'");
        auto 主体 = 解析代码块();
        return std::make_unique<遍历语句>(变量名, std::move(数组表达式), std::move(主体));
    }

    if (当前.类型 == 标记类型::结构体) {
        前进();
        期望类型(标记类型::标识符, "结构体名应为标识符");
        std::string 名称 = _当前标记.值;
        前进();
        期望(标记类型::左花括号, "结构体后应有'{'");
        std::vector<结构体成员> 成员列表;
        while (_当前标记.类型 != 标记类型::右花括号 && _当前标记.类型 != 标记类型::文件结束) {
            期望类型(标记类型::标识符, "成员名应为标识符");
            std::string 成员名 = _当前标记.值;
            前进();
            期望(标记类型::冒号, "成员名后应有':'");
            std::string 类型名;
            if (_当前标记.类型 == 标记类型::整数类型 || _当前标记.类型 == 标记类型::浮点类型 ||
                _当前标记.类型 == 标记类型::布尔类型 || _当前标记.类型 == 标记类型::标识符) {
                类型名 = _当前标记.值;
                前进();
            } else {
                期望类型(标记类型::标识符, "成员类型应为类型名");
            }
            期望(标记类型::分号, "成员声明后应有';'");
            成员列表.push_back({成员名, 类型名});
        }
        期望(标记类型::右花括号, "结构体定义应以'}'结束");
        return std::make_unique<结构体定义语句>(名称, std::move(成员列表));
    }

    if (当前.类型 == 标记类型::打印) {
        前进();
        期望(标记类型::左括号, "打印后应有'('");
        auto 值 = 解析表达式();
        期望(标记类型::右括号, "打印参数后应有')'");
        期望(标记类型::分号, "打印语句后应有';'");
        return std::make_unique<打印语句>(std::move(值));
    }

    if (当前.类型 == 标记类型::左花括号) {
        auto 语句列表 = 解析代码块();
        return std::make_unique<代码块语句>(std::move(语句列表));
    }

    throw std::runtime_error("语句中意外标记 '" + 当前.值 + "'（行 " + std::to_string(当前.行号) + "）");
}

std::unique_ptr<函数> 语法分析器::解析函数() {
    期望(标记类型::函数, "函数应以'函数'开头");
    std::string 函数名 = _当前标记.值;
    前进();

    // 解析类型参数 <T, U, ...>
    std::vector<std::string> 类型参数列表;
    if (_当前标记.类型 == 标记类型::小于) {
        前进();
        if (_当前标记.类型 == 标记类型::标识符) {
            类型参数列表.push_back(_当前标记.值);
            前进();
            while (_当前标记.类型 == 标记类型::逗号) {
                前进();
                期望类型(标记类型::标识符, "类型参数名应为标识符");
                类型参数列表.push_back(_当前标记.值);
                前进();
            }
        }
        期望(标记类型::大于, "类型参数后应有'>'");
    }

    期望(标记类型::左括号, "函数名后应有'('");
    std::vector<函数参数> 参数列表;
    if (_当前标记.类型 == 标记类型::标识符) {
        std::string 参数名 = _当前标记.值;
        std::string 参数类型;
        前进();
        if (_当前标记.类型 == 标记类型::冒号) {
            前进();
            参数类型 = _当前标记.值;
            if (_当前标记.类型 == 标记类型::整数类型 || _当前标记.类型 == 标记类型::浮点类型 ||
                _当前标记.类型 == 标记类型::布尔类型 || _当前标记.类型 == 标记类型::标识符) {
                前进();
            } else {
                期望类型(标记类型::标识符, "参数类型应为类型名");
            }
            // 检查数组类型注解 []
            if (_当前标记.类型 == 标记类型::左方括号) {
                前进();
                期望(标记类型::右方括号, "数组类型后应有']'");
                参数类型 = 参数类型 + "[]";
            }
        }
        std::unique_ptr<表达式> 默认值;
        if (_当前标记.类型 == 标记类型::等于) {
            前进();
            默认值 = 解析表达式();
        }
        bool 是否变长 = false;
        if (_当前标记.类型 == 标记类型::省略号) {
            是否变长 = true;
            前进();
        }
        参数列表.push_back({参数名, 参数类型, std::move(默认值), 是否变长});
        while (_当前标记.类型 == 标记类型::逗号) {
            前进();
            期望类型(标记类型::标识符, "参数名应为标识符");
            参数名 = _当前标记.值;
            参数类型.clear();
            前进();
            if (_当前标记.类型 == 标记类型::冒号) {
                前进();
                参数类型 = _当前标记.值;
                if (_当前标记.类型 == 标记类型::整数类型 || _当前标记.类型 == 标记类型::浮点类型 ||
                    _当前标记.类型 == 标记类型::布尔类型 || _当前标记.类型 == 标记类型::标识符) {
                    前进();
                } else {
                    期望类型(标记类型::标识符, "参数类型应为类型名");
                }
            }
            std::unique_ptr<表达式> 默认值;
            if (_当前标记.类型 == 标记类型::等于) {
                前进();
                默认值 = 解析表达式();
            }
            bool 是否变长 = false;
            if (_当前标记.类型 == 标记类型::省略号) {
                是否变长 = true;
                前进();
            }
            参数列表.push_back({参数名, 参数类型, std::move(默认值), 是否变长});
        }
    }
    期望(标记类型::右括号, "函数参数后应有')'");

    std::string 返回类型;
    if (_当前标记.类型 == 标记类型::冒号) {
        前进();
        返回类型 = _当前标记.值;
        if (_当前标记.类型 == 标记类型::整数类型 || _当前标记.类型 == 标记类型::浮点类型 ||
            _当前标记.类型 == 标记类型::布尔类型 || _当前标记.类型 == 标记类型::字符串类型 ||
            _当前标记.类型 == 标记类型::标识符) {
            前进();
        } else if (_当前标记.类型 == 标记类型::空) {
            前进();
        } else {
            throw std::runtime_error("应有返回类型");
        }
    }

    auto 主体 = 解析代码块();
    return std::make_unique<函数>(函数名, std::move(类型参数列表), std::move(参数列表), 返回类型, std::move(主体));
}

std::unique_ptr<程序> 语法分析器::解析程序() {
    auto 程序 = std::make_unique<struct 程序>();
    while (_当前标记.类型 != 标记类型::文件结束) {
        if (_当前标记.类型 == 标记类型::变量) {
            前进();
            期望类型(标记类型::标识符, "变量后应有标识符（变量名）");
            std::string 变量名 = _当前标记.值;
            前进();
            if (_当前标记.类型 == 标记类型::冒号) {
                前进();
                if (_当前标记.类型 == 标记类型::整数类型 || _当前标记.类型 == 标记类型::布尔类型) {
                    前进();
                } else {
                    期望类型(标记类型::标识符, "类型注解应为类型名");
                    前进();
                }
            }
            期望(标记类型::等于, "变量名后应有'='");
            auto 初始值 = 解析表达式();
            期望(标记类型::分号, "变量初始化后应有';'");
            auto 声明 = std::make_unique<全局变量声明>();
            声明->变量名 = 变量名;
            声明->初始值 = std::move(初始值);
            程序->全局变量.push_back(std::move(声明));
        } else if (_当前标记.类型 == 标记类型::结构体) {
            // 全局结构体定义
            前进();
            期望类型(标记类型::标识符, "结构体名应为标识符");
            std::string 名称 = _当前标记.值;
            前进();
            期望(标记类型::左花括号, "结构体后应有'{'");
            std::vector<结构体成员> 成员列表;
            while (_当前标记.类型 != 标记类型::右花括号 && _当前标记.类型 != 标记类型::文件结束) {
                期望类型(标记类型::标识符, "成员名应为标识符");
                std::string 成员名 = _当前标记.值;
                前进();
                期望(标记类型::冒号, "成员名后应有':'");
                std::string 类型名 = _当前标记.值;
                if (_当前标记.类型 == 标记类型::整数类型 || _当前标记.类型 == 标记类型::浮点类型 ||
                    _当前标记.类型 == 标记类型::布尔类型 || _当前标记.类型 == 标记类型::标识符) {
                    前进();
                } else {
                    期望类型(标记类型::标识符, "成员类型应为类型名");
                }
                期望(标记类型::分号, "成员声明后应有';'");
                成员列表.push_back({成员名, 类型名});
            }
            期望(标记类型::右花括号, "结构体定义应以'}'结束");
            程序->结构体定义列表.push_back({名称, std::move(成员列表)});
        } else if (_当前标记.类型 == 标记类型::导入) {
            前进();
            期望类型(标记类型::字符串, "导入后应为文件路径字符串");
            std::string 模块名 = _当前标记.值;
            前进();
            期望(标记类型::分号, "导入后应有';'");
            导入列表.push_back(模块名);
        } else if (_当前标记.类型 == 标记类型::枚举) {
            // 全局枚举定义
            前进();
            期望类型(标记类型::标识符, "枚举名应为标识符");
            std::string 名称 = _当前标记.值;
            前进();
            期望(标记类型::左花括号, "枚举后应有'{'");
            std::vector<std::string> 成员列表;
            while (_当前标记.类型 != 标记类型::右花括号 && _当前标记.类型 != 标记类型::文件结束) {
                期望类型(标记类型::标识符, "枚举成员名应为标识符");
                成员列表.push_back(_当前标记.值);
                前进();
                if (_当前标记.类型 == 标记类型::逗号) 前进();
            }
            期望(标记类型::右花括号, "枚举定义应以'}'结束");
            程序->枚举定义列表.push_back({名称, std::move(成员列表)});
        } else {
            程序->函数列表.push_back(解析函数());
        }
    }
    return 程序;
}
