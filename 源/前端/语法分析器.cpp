std::unique_ptr<表达式> 语法分析器::解析管道表达式() {
    // 调用位异或级别（跳过位或），在管道层面处理 |
    auto 左 = 解析位异或表达式();

    // 检查管道操作符 |
    while (_当前标记.类型 == 标记类型::位或) {
        // 预览下一个标记，判断是管道还是位或
        // 如果 | 后面是标识符（函数名）或 (（映射），则是管道
        // 否则是位或运算
        size_t 保存位置 = _词法分析器.获取位置();
        int 保存行号 = _词法分析器.获取当前行();
        标记 保存标记 = _当前标记;

        前进();  // 跳过 |

        // 解析可选的参数映射 () - 可以在函数名之前
        std::unordered_map<std::string, std::string> 映射表;
        if (_当前标记.类型 == 标记类型::左括号) {
            前进();
            // 解析映射：左返回名=右参数名
            if (_当前标记.类型 == 标记类型::标识符) {
                std::string 左名 = _当前标记.值;
                std::string 右名;
                前进();
                if (_当前标记.类型 == 标记类型::等于) {
                    前进();
                    期望类型(标记类型::标识符, "映射右侧应为标识符");
                    右名 = _当前标记.值;
                    映射表[左名] = 右名;
                    前进();
                }
                while (_当前标记.类型 == 标记类型::逗号) {
                    前进();
                    期望类型(标记类型::标识符, "映射左侧应为标识符");
                    左名 = _当前标记.值;
                    前进();
                    期望(标记类型::等于, "映射应有'='");
                    期望类型(标记类型::标识符, "映射右侧应为标识符");
                    右名 = _当前标记.值;
                    映射表[左名] = 右名;
                    前进();
                }
            }
            期望(标记类型::右括号, "参数映射后应有')'");
        }

        // 检查是否是函数名（标识符）
        bool 是函数名 = (_当前标记.类型 == 标记类型::标识符);

        if (是函数名 || !映射表.empty()) {
            // 如果有映射但没有函数名，需要检查是否是管道
            if (!是函数名 && !映射表.empty()) {
                // 有映射但没有函数名，回溯
                _词法分析器.设置位置(保存位置);
                _词法分析器.设置当前行(保存行号);
                _当前标记 = 保存标记;
                auto 右 = 解析位异或表达式();
                左 = std::make_unique<二元运算表达式>(二元操作符::位或, std::move(左), std::move(右));
                continue;
            }
            // 可能是管道操作符
            std::string 右函数名 = _当前标记.值;
            前进();

            // 解析右边函数的额外参数（可选）
            std::vector<std::unique_ptr<表达式>> 右参数;
            if (_当前标记.类型 == 标记类型::左括号) {
                前进();
                if (_当前标记.类型 != 标记类型::右括号) {
                    右参数.push_back(解析表达式());
                    while (_当前标记.类型 == 标记类型::逗号) {
                        前进();
                        右参数.push_back(解析表达式());
                    }
                }
                期望(标记类型::右括号, "函数参数后应有')'");
            }

            左 = std::make_unique<管道调用表达式>(std::move(左), 右函数名, std::move(右参数), std::move(映射表));
        } else {
            // 不是管道，回溯并作为位或处理
            _词法分析器.设置位置(保存位置);
            _词法分析器.设置当前行(保存行号);
            _当前标记 = 保存标记;

            // 作为位或运算处理
            auto 右 = 解析位异或表达式();
            左 = std::make_unique<二元运算表达式>(二元操作符::位或, std::move(左), std::move(右));
        }
    }

    return 左;
}

