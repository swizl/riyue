#include "字节码编译器.h"
#include <stdexcept>
#include <iostream>

字节码 字节码编译器::编译(const 程序& 程序) {
    // 第一遍：注册所有函数签名（支持前向引用）
    for (const auto& 函数 : 程序.函数列表) {
        函数信息 信息;
        信息.名称 = 函数->名称;
        信息.参数数量 = static_cast<uint8_t>(函数->参数列表.size());
        结果.函数表.push_back(信息);
    }

    // 注册全局结构体和枚举定义
    for (const auto& [名称, 成员列表] : 程序.结构体定义列表) {
        std::unordered_map<std::string, int> 成员索引;
        for (size_t i = 0; i < 成员列表.size(); i++) {
            成员索引[成员列表[i].名称] = static_cast<int>(i);
        }
        结构体定义映射[名称] = 成员索引;
    }
    for (const auto& [名称, 成员列表] : 程序.枚举定义列表) {
        std::unordered_map<std::string, int> 成员值;
        for (size_t i = 0; i < 成员列表.size(); i++) {
            成员值[成员列表[i]] = static_cast<int>(i);
        }
        结构体定义映射[名称] = 成员值;
    }

    // 第二遍：编译所有函数体
    for (size_t 函数索引 = 0; 函数索引 < 程序.函数列表.size(); 函数索引++) {
        const auto& 函数 = 程序.函数列表[函数索引];
        当前函数索引 = static_cast<int>(函数索引);
        当前函数 = &结果.函数表[函数索引];

        下一个寄存器 = 0;
        最大寄存器 = 0;
        变量映射.clear();
        浮点变量映射.clear();
        字符串变量映射.clear();
        作用域栈.clear();
        进入作用域();

        // 分配参数寄存器
        for (const auto& 参数 : 函数->参数列表) {
            声明变量(参数.名称);
        }

        // 编译函数体
        编译代码块(函数->主体);

        // 添加返回
        if (!函数->返回类型.empty() && 函数->返回类型 != "空") {
            uint8_t 零寄存器 = 分配寄存器();
            发射(指令::双操作数(操作码::加载常量, 零寄存器, static_cast<uint8_t>(结果.添加常量(0))));
            发射(指令::单操作数(操作码::返回值, 零寄存器));
        } else {
            发射(指令::零操作数(操作码::返回空));
        }

        当前函数->最大寄存器 = 最大寄存器;

        退出作用域();
    }

    // 设置入口函数（最后一个用户函数，而非lambda）
    结果.入口函数索引 = static_cast<int>(程序.函数列表.size()) - 1;

    // 添加全局变量初始化函数
    if (!程序.全局变量.empty()) {
        函数信息 初始化信息;
        初始化信息.名称 = "__初始化全局变量";
        初始化信息.参数数量 = 0;

        当前函数索引 = static_cast<int>(结果.函数表.size());
        结果.函数表.push_back(初始化信息);
        当前函数 = &结果.函数表.back();

        下一个寄存器 = 0;
        最大寄存器 = 0;
        变量映射.clear();
        浮点变量映射.clear();
        字符串变量映射.clear();
        作用域栈.clear();
        进入作用域();

        for (const auto& 全局变量 : 程序.全局变量) {
            uint8_t 值寄存器 = 分配寄存器();
            if (全局变量->初始值 && 全局变量->初始值->类型 == 表达式类型::整数) {
                int 值 = static_cast<const 整数表达式&>(*全局变量->初始值).值;
                发射(指令::双操作数(操作码::加载常量, 值寄存器, static_cast<uint8_t>(结果.添加常量(值))));
            } else if (全局变量->初始值 && 全局变量->初始值->类型 == 表达式类型::布尔值) {
                bool 值 = static_cast<const 布尔表达式&>(*全局变量->初始值).值;
                发射(指令::双操作数(操作码::加载常量, 值寄存器, static_cast<uint8_t>(结果.添加常量(值 ? 1 : 0))));
            } else {
                发射(指令::双操作数(操作码::加载常量, 值寄存器, static_cast<uint8_t>(结果.添加常量(0))));
            }
            uint8_t 变量索引 = 声明变量(全局变量->变量名);
            发射(指令::双操作数(操作码::存储变量, 变量索引, 值寄存器));
        }

        发射(指令::零操作数(操作码::返回空));
        当前函数->最大寄存器 = 最大寄存器;
        退出作用域();
    }

    return 结果;
}

void 字节码编译器::编译表达式(const 表达式& 表达式, uint8_t 目标寄存器) {
    switch (表达式.类型) {
        case 表达式类型::整数: {
            int 值 = static_cast<const 整数表达式&>(表达式).值;
            int 索引 = 结果.添加常量(值);
            if (索引 > 255) throw std::runtime_error("常量池溢出：超过256个常量");
            发射(指令::双操作数(操作码::加载常量, 目标寄存器, static_cast<uint8_t>(索引)));
            break;
        }
        case 表达式类型::浮点数: {
            double 值 = static_cast<const 浮点表达式&>(表达式).值;
            int 索引 = 结果.添加浮点常量(值);
            if (索引 > 255) throw std::runtime_error("常量池溢出：超过256个常量");
            发射(指令::双操作数(操作码::加载常量, 目标寄存器, static_cast<uint8_t>(索引)));
            break;
        }
        case 表达式类型::布尔值: {
            bool 值 = static_cast<const 布尔表达式&>(表达式).值;
            int 索引 = 结果.添加常量(值 ? 1 : 0);
            if (索引 > 255) throw std::runtime_error("常量池溢出：超过256个常量");
            发射(指令::双操作数(操作码::加载常量, 目标寄存器, static_cast<uint8_t>(索引)));
            break;
        }
        case 表达式类型::字符串: {
            const std::string& 值 = static_cast<const 字符串表达式&>(表达式).值;
            int 常量索引 = 结果.添加字符串常量(值);
            if (常量索引 > 255) throw std::runtime_error("常量池溢出：超过256个常量");
            发射(指令::双操作数(操作码::加载字符串, 目标寄存器, static_cast<uint8_t>(常量索引)));
            break;
        }
        case 表达式类型::变量: {
            const auto& 变量 = static_cast<const 变量表达式&>(表达式);
            int 索引 = 查找变量(变量.名称);
            if (索引 < 0) throw std::runtime_error("未定义的变量: " + 变量.名称);
            发射(指令::双操作数(操作码::加载变量, 目标寄存器, static_cast<uint8_t>(索引)));
            break;
        }
        case 表达式类型::一元运算: {
            const auto& 一元 = static_cast<const 一元运算表达式&>(表达式);
            uint8_t 操作数寄存器 = 分配寄存器();
            编译表达式(*一元.操作数, 操作数寄存器);
            if (一元.操作符 == 一元操作符::逻辑非) {
                发射(指令::双操作数(操作码::逻辑非, 目标寄存器, 操作数寄存器));
            } else {
                // 检查是否为浮点取负
                bool 是浮点 = false;
                if (一元.操作数->类型 == 表达式类型::浮点数) 是浮点 = true;
                else if (一元.操作数->类型 == 表达式类型::变量) 是浮点 = 是浮点变量(static_cast<const 变量表达式&>(*一元.操作数).名称);
                发射(指令::双操作数(是浮点 ? 操作码::浮点取负 : 操作码::取负, 目标寄存器, 操作数寄存器));
            }
            释放寄存器();
            break;
        }
        case 表达式类型::二元运算: {
            const auto& 二元 = static_cast<const 二元运算表达式&>(表达式);

            // 短路求值
            if (二元.操作符 == 二元操作符::逻辑与) {
                编译表达式(*二元.左操作数, 目标寄存器);
                size_t 假跳转位置 = 当前位置();
                发射(指令::条件跳转(操作码::假跳转, 目标寄存器, 0));
                编译表达式(*二元.右操作数, 目标寄存器);
                回填跳转(假跳转位置, static_cast<int16_t>(当前位置() - 假跳转位置 - 1));
                break;
            }
            if (二元.操作符 == 二元操作符::逻辑或) {
                编译表达式(*二元.左操作数, 目标寄存器);
                size_t 假跳转位置 = 当前位置();
                发射(指令::条件跳转(操作码::假跳转, 目标寄存器, 0));
                // 左为真，跳过右操作数
                size_t 真跳转位置 = 当前位置();
                发射(指令::跳转指令(操作码::跳转, 0));
                // 左为假，计算右操作数
                回填跳转(假跳转位置, static_cast<int16_t>(当前位置() - 假跳转位置 - 1));
                编译表达式(*二元.右操作数, 目标寄存器);
                回填跳转(真跳转位置, static_cast<int16_t>(当前位置() - 真跳转位置 - 1));
                break;
            }

            uint8_t 左寄存器 = 分配寄存器();
            编译表达式(*二元.左操作数, 左寄存器);
            uint8_t 右寄存器 = 分配寄存器();
            编译表达式(*二元.右操作数, 右寄存器);

            // 字符串拼接
            bool 左字符串 = 二元.左操作数->类型 == 表达式类型::字符串;
            bool 右字符串 = 二元.右操作数->类型 == 表达式类型::字符串;
            if (二元.左操作数->类型 == 表达式类型::变量) 左字符串 = 是字符串变量(static_cast<const 变量表达式&>(*二元.左操作数).名称);
            if (二元.右操作数->类型 == 表达式类型::变量) 右字符串 = 是字符串变量(static_cast<const 变量表达式&>(*二元.右操作数).名称);
            if (二元.操作符 == 二元操作符::加法 && (左字符串 || 右字符串)) {
                发射(指令::三操作数(操作码::字符串拼接, 目标寄存器, 左寄存器, 右寄存器));
                释放寄存器();
                释放寄存器();
                break;
            }

            // 检查是否为浮点运算
            bool 左浮点 = false, 右浮点 = false;
            if (二元.左操作数->类型 == 表达式类型::浮点数) 左浮点 = true;
            else if (二元.左操作数->类型 == 表达式类型::变量) 左浮点 = 是浮点变量(static_cast<const 变量表达式&>(*二元.左操作数).名称);
            else if (二元.左操作数->类型 == 表达式类型::函数调用) 左浮点 = true; // 假设函数调用可能返回浮点
            if (二元.右操作数->类型 == 表达式类型::浮点数) 右浮点 = true;
            else if (二元.右操作数->类型 == 表达式类型::变量) 右浮点 = 是浮点变量(static_cast<const 变量表达式&>(*二元.右操作数).名称);
            else if (二元.右操作数->类型 == 表达式类型::函数调用) 右浮点 = true;

            if (左浮点 || 右浮点) {
                // 浮点运算：需要将整数操作数转换为浮点
                if (!左浮点) {
                    uint8_t 浮点寄存器 = 分配寄存器();
                    发射(指令::双操作数(操作码::整数转浮点, 浮点寄存器, 左寄存器));
                    左寄存器 = 浮点寄存器;
                }
                if (!右浮点) {
                    uint8_t 浮点寄存器 = 分配寄存器();
                    发射(指令::双操作数(操作码::整数转浮点, 浮点寄存器, 右寄存器));
                    右寄存器 = 浮点寄存器;
                }
                操作码 浮点码;
                switch (二元.操作符) {
                    case 二元操作符::加法: 浮点码 = 操作码::浮点加法; break;
                    case 二元操作符::减法: 浮点码 = 操作码::浮点减法; break;
                    case 二元操作符::乘法: 浮点码 = 操作码::浮点乘法; break;
                    case 二元操作符::除法: 浮点码 = 操作码::浮点除法; break;
                    case 二元操作符::等于: 浮点码 = 操作码::浮点等于; break;
                    case 二元操作符::不等于: 浮点码 = 操作码::浮点不等于; break;
                    case 二元操作符::小于: 浮点码 = 操作码::浮点小于; break;
                    case 二元操作符::大于: 浮点码 = 操作码::浮点大于; break;
                    case 二元操作符::小于等于: 浮点码 = 操作码::浮点小于等于; break;
                    case 二元操作符::大于等于: 浮点码 = 操作码::浮点大于等于; break;
                    default: throw std::runtime_error("未知浮点二元运算符");
                }
                发射(指令::三操作数(浮点码, 目标寄存器, 左寄存器, 右寄存器));
                释放寄存器();
                释放寄存器();
                break;
            }

            操作码 码;
            switch (二元.操作符) {
                case 二元操作符::加法: 码 = 操作码::加法; break;
                case 二元操作符::减法: 码 = 操作码::减法; break;
                case 二元操作符::乘法: 码 = 操作码::乘法; break;
                case 二元操作符::除法: 码 = 操作码::除法; break;
                case 二元操作符::取模: 码 = 操作码::取模; break;
                case 二元操作符::等于: 码 = 操作码::等于; break;
                case 二元操作符::不等于: 码 = 操作码::不等于; break;
                case 二元操作符::小于: 码 = 操作码::小于; break;
                case 二元操作符::大于: 码 = 操作码::大于; break;
                case 二元操作符::小于等于: 码 = 操作码::小于等于; break;
                case 二元操作符::大于等于: 码 = 操作码::大于等于; break;
                default: throw std::runtime_error("未知二元运算符");
            }
            发射(指令::三操作数(码, 目标寄存器, 左寄存器, 右寄存器));
            释放寄存器();
            释放寄存器();
            break;
        }
        case 表达式类型::函数调用: {
            const auto& 调用 = static_cast<const 函数调用表达式&>(表达式);

            // 内置字符串函数
            if (调用.函数名 == "长度") {
                uint8_t 参数寄存器 = 分配寄存器();
                编译表达式(*调用.参数列表[0], 参数寄存器);
                发射(指令::双操作数(操作码::字符串长度, 目标寄存器, 参数寄存器));
                释放寄存器();
                break;
            }
            if (调用.函数名 == "查找") {
                uint8_t 左寄存器 = 分配寄存器();
                编译表达式(*调用.参数列表[0], 左寄存器);
                uint8_t 右寄存器 = 分配寄存器();
                编译表达式(*调用.参数列表[1], 右寄存器);
                发射(指令::三操作数(操作码::字符串查找, 目标寄存器, 左寄存器, 右寄存器));
                释放寄存器();
                释放寄存器();
                break;
            }

            // 数学函数
            if (调用.函数名 == "绝对值") {
                uint8_t 参数寄存器 = 分配寄存器();
                编译表达式(*调用.参数列表[0], 参数寄存器);
                发射(指令::双操作数(操作码::绝对值运算, 目标寄存器, 参数寄存器));
                释放寄存器();
                break;
            }
            if (调用.函数名 == "最小值") {
                uint8_t 左寄存器 = 分配寄存器();
                编译表达式(*调用.参数列表[0], 左寄存器);
                uint8_t 右寄存器 = 分配寄存器();
                编译表达式(*调用.参数列表[1], 右寄存器);
                发射(指令::三操作数(操作码::最小值运算, 目标寄存器, 左寄存器, 右寄存器));
                释放寄存器();
                释放寄存器();
                break;
            }
            if (调用.函数名 == "最大值") {
                uint8_t 左寄存器 = 分配寄存器();
                编译表达式(*调用.参数列表[0], 左寄存器);
                uint8_t 右寄存器 = 分配寄存器();
                编译表达式(*调用.参数列表[1], 右寄存器);
                发射(指令::三操作数(操作码::最大值运算, 目标寄存器, 左寄存器, 右寄存器));
                释放寄存器();
                释放寄存器();
                break;
            }

            // 类型转换函数
            if (调用.函数名 == "转整数") {
                uint8_t 参数寄存器 = 分配寄存器();
                编译表达式(*调用.参数列表[0], 参数寄存器);
                发射(指令::双操作数(操作码::浮点转整数, 目标寄存器, 参数寄存器));
                释放寄存器();
                break;
            }
            if (调用.函数名 == "转浮点") {
                uint8_t 参数寄存器 = 分配寄存器();
                编译表达式(*调用.参数列表[0], 参数寄存器);
                发射(指令::双操作数(操作码::整数转浮点, 目标寄存器, 参数寄存器));
                释放寄存器();
                break;
            }
            if (调用.函数名 == "类型") {
                uint8_t 参数寄存器 = 分配寄存器();
                编译表达式(*调用.参数列表[0], 参数寄存器);
                // 基于编译期类型信息返回类型名
                std::string 类型名 = "整数";
                if (调用.参数列表[0]->类型 == 表达式类型::浮点数) 类型名 = "浮点数";
                else if (调用.参数列表[0]->类型 == 表达式类型::字符串) 类型名 = "字符串";
                else if (调用.参数列表[0]->类型 == 表达式类型::变量) {
                    const auto& 变量 = static_cast<const 变量表达式&>(*调用.参数列表[0]);
                    if (是浮点变量(变量.名称)) 类型名 = "浮点数";
                    else if (是字符串变量(变量.名称)) 类型名 = "字符串";
                }
                int 常量索引 = 结果.添加字符串常量(类型名);
                if (常量索引 > 255) throw std::runtime_error("常量池溢出");
                发射(指令::双操作数(操作码::加载字符串, 目标寄存器, static_cast<uint8_t>(常量索引)));
                释放寄存器();
                break;
            }

            // 查找用户函数
            int 函数索引 = -1;
            for (size_t i = 0; i < 结果.函数表.size(); i++) {
                if (结果.函数表[i].名称 == 调用.函数名) { 函数索引 = static_cast<int>(i); break; }
            }

            // 编译参数到临时寄存器
            std::vector<uint8_t> 参数寄存器;
            for (const auto& 参数 : 调用.参数列表) {
                uint8_t reg = 分配寄存器();
                编译表达式(*参数, reg);
                参数寄存器.push_back(reg);
            }

            if (函数索引 >= 0) {
                // 直接调用已知函数
                for (size_t i = 0; i < 参数寄存器.size(); i++) {
                    if (参数寄存器[i] != static_cast<uint8_t>(i)) {
                        发射(指令::双操作数(操作码::复制寄存器, static_cast<uint8_t>(i), 参数寄存器[i]));
                    }
                }
                发射(指令::调用指令(static_cast<uint8_t>(函数索引), static_cast<uint8_t>(调用.参数列表.size()), 目标寄存器));
            } else {
                // 尝试作为闭包调用
                int 变量索引 = 查找变量(调用.函数名);
                if (变量索引 < 0) throw std::runtime_error("未定义的函数: " + 调用.函数名);
                if (!闭包变量映射.count(调用.函数名)) throw std::runtime_error("变量不是闭包: " + 调用.函数名);
                uint8_t 闭包寄存器 = 分配寄存器();
                发射(指令::双操作数(操作码::加载变量, 闭包寄存器, static_cast<uint8_t>(变量索引)));
                // 将闭包寄存器放在参数之前
                发射(指令::双操作数(操作码::复制寄存器, 0, 闭包寄存器));
                释放寄存器();
                for (size_t i = 0; i < 参数寄存器.size(); i++) {
                    if (参数寄存器[i] != static_cast<uint8_t>(i + 1)) {
                        发射(指令::双操作数(操作码::复制寄存器, static_cast<uint8_t>(i + 1), 参数寄存器[i]));
                    }
                }
                发射(指令::三操作数(操作码::调用闭包, 0, static_cast<uint8_t>(调用.参数列表.size()), 目标寄存器));
            }

            for (size_t i = 0; i < 参数寄存器.size(); i++) 释放寄存器();
            break;
        }
        case 表达式类型::数组字面量: {
            const auto& 数组 = static_cast<const 数组字面量表达式&>(表达式);
            uint8_t 大小寄存器 = 分配寄存器();
            发射(指令::双操作数(操作码::加载常量, 大小寄存器, static_cast<uint8_t>(结果.添加常量(static_cast<int>(数组.元素列表.size())))));
            发射(指令::双操作数(操作码::创建数组, 目标寄存器, 大小寄存器));
            释放寄存器();
            // 存储每个元素
            for (size_t i = 0; i < 数组.元素列表.size(); i++) {
                uint8_t 索引寄存器 = 分配寄存器();
                发射(指令::双操作数(操作码::加载常量, 索引寄存器, static_cast<uint8_t>(结果.添加常量(static_cast<int>(i)))));
                uint8_t 值寄存器 = 分配寄存器();
                编译表达式(*数组.元素列表[i], 值寄存器);
                发射(指令::三操作数(操作码::存储数组元素, 目标寄存器, 索引寄存器, 值寄存器));
                释放寄存器();
                释放寄存器();
            }
            break;
        }
        case 表达式类型::下标访问: {
            const auto& 下标 = static_cast<const 下标访问表达式&>(表达式);
            uint8_t 数组寄存器 = 分配寄存器();
            // 加载数组变量
            int 数组索引 = 查找变量(下标.数组名);
            if (数组索引 < 0) throw std::runtime_error("未定义的数组: " + 下标.数组名);
            发射(指令::双操作数(操作码::加载变量, 数组寄存器, static_cast<uint8_t>(数组索引)));
            uint8_t 索引寄存器 = 分配寄存器();
            编译表达式(*下标.索引, 索引寄存器);
            发射(指令::三操作数(操作码::加载数组元素, 目标寄存器, 数组寄存器, 索引寄存器));
            释放寄存器();
            释放寄存器();
            break;
        }
        case 表达式类型::匿名函数: {
            const auto& 匿名 = static_cast<const 匿名函数表达式&>(表达式);
            // 收集自由变量（简化：检查当前作用域中的变量）
            std::vector<std::string> 参数名列表;
            for (const auto& 参数 : 匿名.参数列表) 参数名列表.push_back(参数.名称);
            std::vector<std::string> 捕获变量名;
            std::vector<uint8_t> 捕获寄存器;
            for (const auto& [名, reg] : 变量映射) {
                bool 是参数 = false;
                for (const auto& 参数名 : 参数名列表) { if (参数名 == 名) { 是参数 = true; break; } }
                if (!是参数) {
                    捕获变量名.push_back(名);
                    捕获寄存器.push_back(reg);
                }
            }
            // 编译匿名函数为独立函数
            int 函数索引 = 编译匿名函数(匿名, 捕获变量名);
            // 将捕获变量复制到连续寄存器
            for (size_t i = 0; i < 捕获寄存器.size(); i++) {
                uint8_t 捕获目标 = 分配寄存器();
                发射(指令::双操作数(操作码::复制寄存器, 捕获目标, 捕获寄存器[i]));
            }
            // 发射创建闭包指令（C=捕获数量，捕获变量在目标寄存器之后的连续寄存器中）
            发射(指令::三操作数(操作码::创建闭包, 目标寄存器, static_cast<uint8_t>(函数索引), static_cast<uint8_t>(捕获变量名.size())));
            // 释放捕获变量的临时寄存器
            for (size_t i = 0; i < 捕获变量名.size(); i++) 释放寄存器();
            break;
        }
        case 表达式类型::结构体实例: {
            const auto& 实例 = static_cast<const 结构体实例表达式&>(表达式);
            uint8_t 成员数量 = static_cast<uint8_t>(实例.成员列表.size());
            发射(指令::双操作数(操作码::创建结构体, 目标寄存器, 成员数量));
            for (size_t i = 0; i < 实例.成员列表.size(); i++) {
                uint8_t 值寄存器 = 分配寄存器();
                编译表达式(*实例.成员列表[i].second, 值寄存器);
                int 名称索引 = 结果.添加字符串常量(实例.成员列表[i].first);
                发射(指令::三操作数(操作码::存储成员, 目标寄存器, static_cast<uint8_t>(名称索引), 值寄存器));
                释放寄存器();
            }
            break;
        }
        case 表达式类型::成员访问: {
            const auto& 访问 = static_cast<const 成员访问表达式&>(表达式);
            int 变量索引 = 查找变量(访问.对象名);
            if (变量索引 < 0) throw std::runtime_error("未定义的变量: " + 访问.对象名);
            uint8_t 结构体寄存器 = 分配寄存器();
            发射(指令::双操作数(操作码::加载变量, 结构体寄存器, static_cast<uint8_t>(变量索引)));
            int 名称索引 = 结果.添加字符串常量(访问.成员名);
            发射(指令::三操作数(操作码::加载成员, 目标寄存器, 结构体寄存器, static_cast<uint8_t>(名称索引)));
            释放寄存器();
            break;
        }
        case 表达式类型::枚举成员: {
            const auto& 枚举成员 = static_cast<const 枚举成员表达式&>(表达式);
            // 枚举成员在编译期解析为整数值
            auto defIt = 结构体定义映射.find(枚举成员.枚举名);
            if (defIt != 结构体定义映射.end()) {
                auto memIt = defIt->second.find(枚举成员.成员名);
                if (memIt != defIt->second.end()) {
                    int 常量索引 = 结果.添加常量(memIt->second);
                    发射(指令::双操作数(操作码::加载常量, 目标寄存器, static_cast<uint8_t>(常量索引)));
                    break;
                }
            }
            throw std::runtime_error("未定义的枚举成员: " + 枚举成员.枚举名 + "::" + 枚举成员.成员名);
        }
        default:
            throw std::runtime_error("未支持的表达式类型");
    }
}

void 字节码编译器::编译语句(const 语句& 语句) {
    switch (语句.类型) {
        case 语句类型::变量声明: {
            const auto& 声明 = static_cast<const 变量声明&>(语句);
            uint8_t 值寄存器 = 分配寄存器();
            编译表达式(*声明.初始值, 值寄存器);
            uint8_t 变量索引 = 声明变量(声明.变量名);
            发射(指令::双操作数(操作码::存储变量, 变量索引, 值寄存器));
            // 跟踪变量类型
            if (声明.初始值->类型 == 表达式类型::浮点数) {
                设置浮点变量(声明.变量名);
            } else if (声明.初始值->类型 == 表达式类型::字符串) {
                设置字符串变量(声明.变量名);
            } else if (声明.初始值->类型 == 表达式类型::匿名函数) {
                闭包变量映射[声明.变量名] = true;
            } else if (声明.初始值->类型 == 表达式类型::结构体实例) {
                结构体变量映射[声明.变量名] = true;
            } else if (声明.初始值->类型 == 表达式类型::变量) {
                const auto& 变量 = static_cast<const 变量表达式&>(*声明.初始值);
                if (是浮点变量(变量.名称)) 设置浮点变量(声明.变量名);
                else if (是字符串变量(变量.名称)) 设置字符串变量(声明.变量名);
                else if (闭包变量映射.count(变量.名称)) 闭包变量映射[声明.变量名] = true;
                else if (结构体变量映射.count(变量.名称)) 结构体变量映射[声明.变量名] = true;
            } else if (声明.初始值->类型 == 表达式类型::一元运算) {
                const auto& 一元 = static_cast<const 一元运算表达式&>(*声明.初始值);
                if (一元.操作符 == 一元操作符::取负 && 一元.操作数->类型 == 表达式类型::浮点数) {
                    设置浮点变量(声明.变量名);
                }
            }
            // 注意：不释放寄存器，变量需要持久化
            break;
        }
        case 语句类型::常量声明: {
            const auto& 声明 = static_cast<const 常量声明&>(语句);
            uint8_t 值寄存器 = 分配寄存器();
            编译表达式(*声明.初始值, 值寄存器);
            uint8_t 变量索引 = 声明变量(声明.常量名);
            发射(指令::双操作数(操作码::存储变量, 变量索引, 值寄存器));
            if (声明.初始值->类型 == 表达式类型::浮点数) {
                设置浮点变量(声明.常量名);
            } else if (声明.初始值->类型 == 表达式类型::字符串) {
                设置字符串变量(声明.常量名);
            } else if (声明.初始值->类型 == 表达式类型::变量) {
                const auto& 变量 = static_cast<const 变量表达式&>(*声明.初始值);
                if (是浮点变量(变量.名称)) 设置浮点变量(声明.常量名);
                else if (是字符串变量(变量.名称)) 设置字符串变量(声明.常量名);
            }
            break;
        }
        case 语句类型::赋值语句: {
            const auto& 赋值 = static_cast<const 赋值语句&>(语句);
            uint8_t 值寄存器 = 分配寄存器();
            编译表达式(*赋值.值表达式, 值寄存器);
            int 变量索引 = 查找变量(赋值.变量名);
            if (变量索引 < 0) throw std::runtime_error("未定义的变量: " + 赋值.变量名);
            发射(指令::双操作数(操作码::存储变量, static_cast<uint8_t>(变量索引), 值寄存器));
            // 传播类型信息
            if (赋值.值表达式->类型 == 表达式类型::浮点数) {
                设置浮点变量(赋值.变量名);
            } else if (赋值.值表达式->类型 == 表达式类型::字符串) {
                设置字符串变量(赋值.变量名);
            } else if (赋值.值表达式->类型 == 表达式类型::变量) {
                const auto& 变量 = static_cast<const 变量表达式&>(*赋值.值表达式);
                if (是浮点变量(变量.名称)) 设置浮点变量(赋值.变量名);
                else if (是字符串变量(变量.名称)) 设置字符串变量(赋值.变量名);
            }
            释放寄存器();
            break;
        }
        case 语句类型::打印语句: {
            const auto& 打印 = static_cast<const 打印语句&>(语句);
            uint8_t 值寄存器 = 分配寄存器();
            编译表达式(*打印.值表达式, 值寄存器);
            // 检查是否为浮点变量
            bool 是浮点 = false;
            if (打印.值表达式->类型 == 表达式类型::浮点数) {
                是浮点 = true;
            } else if (打印.值表达式->类型 == 表达式类型::变量) {
                是浮点 = 是浮点变量(static_cast<const 变量表达式&>(*打印.值表达式).名称);
            }
            发射(指令::单操作数(是浮点 ? 操作码::打印浮点 : 操作码::打印, 值寄存器));
            释放寄存器();
            break;
        }
        case 语句类型::返回语句: {
            const auto& 返回 = static_cast<const 返回语句&>(语句);
            if (返回.返回值) {
                uint8_t 值寄存器 = 分配寄存器();
                编译表达式(*返回.返回值, 值寄存器);
                发射(指令::单操作数(操作码::返回值, 值寄存器));
                释放寄存器();
            } else {
                发射(指令::零操作数(操作码::返回空));
            }
            break;
        }
        case 语句类型::如果语句: {
            const auto& 如果 = static_cast<const 如果语句&>(语句);
            uint8_t 条件寄存器 = 分配寄存器();
            编译表达式(*如果.条件, 条件寄存器);

            size_t 假跳转位置 = 当前位置();
            发射(指令::条件跳转(操作码::假跳转, 条件寄存器, 0));
            释放寄存器();

            编译代码块(如果.then块);
            std::vector<size_t> 跳出位置列表;
            跳出位置列表.push_back(当前位置());
            发射(指令::跳转指令(操作码::跳转, 0));

            回填跳转(假跳转位置, static_cast<int16_t>(当前位置() - 假跳转位置 - 1));

            for (const auto& 分支 : 如果.否则如果列表) {
                uint8_t elif条件 = 分配寄存器();
                编译表达式(*分支.条件, elif条件);
                size_t elif假跳转 = 当前位置();
                发射(指令::条件跳转(操作码::假跳转, elif条件, 0));
                释放寄存器();
                编译代码块(分支.主体);
                跳出位置列表.push_back(当前位置());
                发射(指令::跳转指令(操作码::跳转, 0));
                回填跳转(elif假跳转, static_cast<int16_t>(当前位置() - elif假跳转 - 1));
            }

            if (!如果.else块.empty()) {
                编译代码块(如果.else块);
            }

            // 回填所有跳出跳转到合并点
            for (size_t 跳出位置 : 跳出位置列表) {
                回填跳转(跳出位置, static_cast<int16_t>(当前位置() - 跳出位置 - 1));
            }
            break;
        }
        case 语句类型::循环语句: {
            const auto& 循环 = static_cast<const 循环语句&>(语句);

            // 编译初始化
            if (循环.初始化) {
                进入作用域();
                编译语句(*循环.初始化);
            }

            size_t 条件位置 = 当前位置();
            循环上下文 循环上下文;
            循环上下文.继续目标 = 条件位置; // 默认：步进后跳到条件
            循环栈.push_back(循环上下文);

            // 编译条件（如果有）
            size_t 条件跳转位置 = 0;
            if (循环.条件) {
                uint8_t 条件寄存器 = 分配寄存器();
                编译表达式(*循环.条件, 条件寄存器);
                条件跳转位置 = 当前位置();
                发射(指令::条件跳转(操作码::假跳转, 条件寄存器, 0));
                释放寄存器();
            }

            // 编译循环体
            编译代码块(循环.主体);

            // 编译步进（如果有）
            size_t 步进位置 = 当前位置();
            if (循环.步进) {
                编译语句(*循环.步进);
                // 更新继续目标到步进之后
                for (auto& ctx : 循环栈) {
                    if (&ctx == &循环栈.back()) {
                        ctx.继续目标 = 步进位置;
                    }
                }
            }

            // 跳回条件检查
            发射(指令::跳转指令(操作码::跳转, static_cast<int16_t>(条件位置 - 当前位置() - 1)));

            // 回填条件假跳转
            if (循环.条件) {
                回填跳转(条件跳转位置, static_cast<int16_t>(当前位置() - 条件跳转位置 - 1));
            }

            // 回填中断跳转
            for (size_t 跳转 : 循环栈.back().中断跳转) {
                回填跳转(跳转, static_cast<int16_t>(当前位置() - 跳转 - 1));
            }
            循环栈.pop_back();

            if (循环.初始化) {
                退出作用域();
            }
            break;
        }
        case 语句类型::当循环语句: {
            const auto& 当循环 = static_cast<const 当循环语句&>(语句);
            size_t 条件位置 = 当前位置();
            循环上下文 上下文;
            上下文.继续目标 = 条件位置;
            循环栈.push_back(上下文);

            uint8_t 条件寄存器 = 分配寄存器();
            编译表达式(*当循环.条件, 条件寄存器);
            size_t 假跳转 = 当前位置();
            发射(指令::条件跳转(操作码::假跳转, 条件寄存器, 0));
            释放寄存器();

            编译代码块(当循环.主体);

            发射(指令::跳转指令(操作码::跳转, static_cast<int16_t>(条件位置 - 当前位置() - 1)));
            回填跳转(假跳转, static_cast<int16_t>(当前位置() - 假跳转 - 1));

            for (size_t 跳转 : 循环栈.back().中断跳转) {
                回填跳转(跳转, static_cast<int16_t>(当前位置() - 跳转 - 1));
            }
            循环栈.pop_back();
            break;
        }
        case 语句类型::中断语句: {
            if (循环栈.empty()) throw std::runtime_error("'中断'必须在循环内使用");
            size_t 跳转位置 = 当前位置();
            发射(指令::跳转指令(操作码::跳转, 0));
            循环栈.back().中断跳转.push_back(跳转位置);
            break;
        }
        case 语句类型::继续语句: {
            if (循环栈.empty()) throw std::runtime_error("'继续'必须在循环内使用");
            size_t 目标 = 循环栈.back().继续目标;
            发射(指令::跳转指令(操作码::跳转, static_cast<int16_t>(目标 - 当前位置() - 1)));
            break;
        }
        case 语句类型::表达式语句: {
            uint8_t 临时寄存器 = 分配寄存器();
            编译表达式(*static_cast<const 表达式语句&>(语句).值表达式, 临时寄存器);
            释放寄存器();
            break;
        }
        case 语句类型::代码块: {
            进入作用域();
            编译代码块(static_cast<const 代码块语句&>(语句).语句列表);
            退出作用域();
            break;
        }
        case 语句类型::下标赋值语句: {
            const auto& 下标赋值 = static_cast<const 下标赋值语句&>(语句);
            // 直接使用变量的寄存器，不加载到临时寄存器
            int 数组索引 = 查找变量(下标赋值.数组名);
            if (数组索引 < 0) throw std::runtime_error("未定义的数组: " + 下标赋值.数组名);
            uint8_t 索引寄存器 = 分配寄存器();
            编译表达式(*下标赋值.索引, 索引寄存器);
            uint8_t 值寄存器 = 分配寄存器();
            编译表达式(*下标赋值.值表达式, 值寄存器);
            发射(指令::三操作数(操作码::存储数组元素, static_cast<uint8_t>(数组索引), 索引寄存器, 值寄存器));
            释放寄存器();
            释放寄存器();
            break;
        }
        case 语句类型::匹配语句: {
            const auto& 匹配 = static_cast<const 匹配语句&>(语句);
            uint8_t 值寄存器 = 分配寄存器();
            编译表达式(*匹配.匹配值, 值寄存器);
            std::vector<size_t> 跳出位置列表;
            for (const auto& 分支 : 匹配.分支列表) {
                if (!分支.条件) {
                    // 默认分支
                    进入作用域();
                    编译代码块(分支.主体);
                    退出作用域();
                    continue;
                }
                uint8_t 分支值寄存器 = 分配寄存器();
                编译表达式(*分支.条件, 分支值寄存器);
                uint8_t 比较结果寄存器 = 分配寄存器();
                发射(指令::三操作数(操作码::等于, 比较结果寄存器, 值寄存器, 分支值寄存器));
                释放寄存器();
                size_t 假跳转位置 = 当前位置();
                发射(指令::条件跳转(操作码::假跳转, 比较结果寄存器, 0));
                释放寄存器();
                进入作用域();
                编译代码块(分支.主体);
                退出作用域();
                跳出位置列表.push_back(当前位置());
                发射(指令::跳转指令(操作码::跳转, 0));
                回填跳转(假跳转位置, static_cast<int16_t>(当前位置() - 假跳转位置 - 1));
            }
            for (size_t 跳出位置 : 跳出位置列表) {
                回填跳转(跳出位置, static_cast<int16_t>(当前位置() - 跳出位置 - 1));
            }
            释放寄存器();
            break;
        }
        case 语句类型::遍历语句: {
            const auto& 遍历 = static_cast<const 遍历语句&>(语句);
            int 数组索引 = -1;
            if (遍历.数组表达式->类型 == 表达式类型::变量) {
                数组索引 = 查找变量(static_cast<const 变量表达式&>(*遍历.数组表达式).名称);
            }
            if (数组索引 < 0) throw std::runtime_error("遍历只支持简单数组变量");
            进入作用域();
            uint8_t 元素变量 = 声明变量(遍历.变量名);
            uint8_t 索引寄存器 = 分配寄存器();
            发射(指令::双操作数(操作码::加载常量, 索引寄存器, static_cast<uint8_t>(结果.添加常量(0))));
            size_t 循环开始 = 当前位置();
            循环上下文 上下文;
            上下文.继续目标 = 循环开始;
            循环栈.push_back(上下文);
            // 加载数组元素
            发射(指令::三操作数(操作码::加载数组元素, 元素变量, static_cast<uint8_t>(数组索引), 索引寄存器));
            编译代码块(遍历.主体);
            // 索引+1
            uint8_t 一寄存器 = 分配寄存器();
            发射(指令::双操作数(操作码::加载常量, 一寄存器, static_cast<uint8_t>(结果.添加常量(1))));
            uint8_t 新索引寄存器 = 分配寄存器();
            发射(指令::三操作数(操作码::加法, 新索引寄存器, 索引寄存器, 一寄存器));
            发射(指令::双操作数(操作码::复制寄存器, 索引寄存器, 新索引寄存器));
            释放寄存器();
            释放寄存器();
            // 检查是否到达数组大小（简化：使用固定大小100）
            uint8_t 大小寄存器 = 分配寄存器();
            发射(指令::双操作数(操作码::加载常量, 大小寄存器, static_cast<uint8_t>(结果.添加常量(100))));
            uint8_t 比较寄存器 = 分配寄存器();
            发射(指令::三操作数(操作码::小于, 比较寄存器, 索引寄存器, 大小寄存器));
            释放寄存器();
            释放寄存器();
            size_t 条件跳转位置 = 当前位置();
            发射(指令::条件跳转(操作码::假跳转, 比较寄存器, 0));
            释放寄存器();
            // 跳回循环开始
            发射(指令::跳转指令(操作码::跳转, static_cast<int16_t>(循环开始 - 当前位置() - 1)));
            // 回填条件跳转
            回填跳转(条件跳转位置, static_cast<int16_t>(当前位置() - 条件跳转位置 - 1));
            // 回填中断跳转
            for (size_t 跳转 : 循环栈.back().中断跳转) {
                回填跳转(跳转, static_cast<int16_t>(当前位置() - 跳转 - 1));
            }
            循环栈.pop_back();
            退出作用域();
            break;
        }
        case 语句类型::结构体定义: {
            const auto& 结构体 = static_cast<const 结构体定义语句&>(语句);
            // 注册结构体定义（成员名到索引的映射）
            std::unordered_map<std::string, int> 成员索引;
            for (size_t i = 0; i < 结构体.成员列表.size(); i++) {
                成员索引[结构体.成员列表[i].名称] = static_cast<int>(i);
            }
            结构体定义映射[结构体.名称] = 成员索引;
            break;
        }
        case 语句类型::枚举定义: {
            const auto& 枚举 = static_cast<const 枚举定义语句&>(语句);
            // 注册枚举定义（成员名到值的映射）
            std::unordered_map<std::string, int> 成员值;
            for (size_t i = 0; i < 枚举.成员列表.size(); i++) {
                成员值[枚举.成员列表[i]] = static_cast<int>(i);
            }
            结构体定义映射[枚举.名称] = 成员值;
            break;
        }
        case 语句类型::导入语句:
            // 这些在全局阶段处理，此处无需操作
            break;
    }
}

void 字节码编译器::编译代码块(const std::vector<std::unique_ptr<语句>>& 语句列表) {
    for (const auto& 语句 : 语句列表) {
        编译语句(*语句);
    }
}

int 字节码编译器::编译匿名函数(const 匿名函数表达式& 匿名, const std::vector<std::string>& 捕获变量名) {
    // 保存当前编译状态
    auto 保存函数索引 = 当前函数索引;
    auto 保存寄存器 = 下一个寄存器;
    auto 保存最大寄存器 = 最大寄存器;
    auto 保存变量映射 = 变量映射;
    auto 保存浮点映射 = 浮点变量映射;
    auto 保存字符串映射 = 字符串变量映射;
    auto 保存作用域栈 = 作用域栈;

    // 创建新函数
    函数信息 新函数;
    新函数.名称 = "lambda_" + std::to_string(结果.函数表.size());
    size_t 参数总数 = 匿名.参数列表.size() + 捕获变量名.size();
    新函数.参数数量 = static_cast<uint8_t>(参数总数);

    当前函数索引 = static_cast<int>(结果.函数表.size());
    结果.函数表.push_back(新函数);
    // push_back可能使之前的所有指针失效，所以用索引访问
    当前函数 = &结果.函数表[当前函数索引];
    下一个寄存器 = 0;
    最大寄存器 = 0;
    变量映射.clear();
    浮点变量映射.clear();
    字符串变量映射.clear();
    作用域栈.clear();
    进入作用域();

    for (size_t i = 0; i < 匿名.参数列表.size(); i++) {
        声明变量(匿名.参数列表[i].名称);
    }
    for (size_t i = 0; i < 捕获变量名.size(); i++) {
        声明变量(捕获变量名[i]);
    }

    编译代码块(匿名.主体);

    if (!匿名.返回类型.empty() && 匿名.返回类型 != "空") {
        uint8_t 零寄存器 = 分配寄存器();
        发射(指令::双操作数(操作码::加载常量, 零寄存器, static_cast<uint8_t>(结果.添加常量(0))));
        发射(指令::单操作数(操作码::返回值, 零寄存器));
    } else {
        发射(指令::零操作数(操作码::返回空));
    }

    当前函数->最大寄存器 = 最大寄存器;
    int 新函数索引 = 当前函数索引;

    // 恢复状态 — 使用索引而非指针，因为push_back可能已使指针失效
    当前函数索引 = 保存函数索引;
    当前函数 = &结果.函数表[保存函数索引];
    下一个寄存器 = 保存寄存器;
    最大寄存器 = 保存最大寄存器;
    变量映射 = std::move(保存变量映射);
    浮点变量映射 = std::move(保存浮点映射);
    字符串变量映射 = std::move(保存字符串映射);
    作用域栈 = std::move(保存作用域栈);

    return 新函数索引;
}
