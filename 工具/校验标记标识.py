#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""校验 源/共享/标记标识表.h 的 id 与 源/前端/词法分析器.h 的 标记类型 是否一致。"""
import re, sys, os

根 = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")

表文本 = open(os.path.join(根, "源", "共享", "标记标识表.h"), encoding="utf-8").read()
enum文本 = open(os.path.join(根, "源", "前端", "词法分析器.h"), encoding="utf-8").read()


def 取表(名):
    m = re.search(r"static const char\* const " + 名 + r"\[[^\]]*\] = \{(.*?)\};", 表文本, re.S)
    return re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(1))


关键字 = 取表("关键字表")
文本标志 = 取表("文本标志表")

m = re.search(r"举型\s+类别\s+标记类型\s*\{(.*?)\};", enum文本, re.S)
枚 = {}
for 行 in m.group(1).splitlines():
    行 = 行.split("//")[0].strip().rstrip(",")
    if not 行 or "=" not in 行:
        continue
    k, v = 行.split("=")
    枚[k.strip()] = int(v.strip())

# 关键字：id = 下标 + 1 → 标记名（枚举里 关键字名与表文本一致，除 空/如果 等带 标记_ 前缀）
关键字名 = ["函数", "标记_空", "标记_如果", "标记_否则", "标记_否则如果", "标记_循环", "标记_当",
        "标记_做", "到", "标记_中断", "标记_继续", "变量", "标记_常量", "标记_返回", "匹配",
        "遍历", "导入", "标记_整数类型", "标记_浮点类型", "标记_布尔类型", "字符串类型",
        "标记_结构体", "标记_枚举", "标记_真", "标记_假", "方法", "标记_尝试", "标记_捕获",
        "标记_抛出", "最终", "协程", "让出", "入"]
标志名 = ["左括号", "右括号", "左花括号", "右花括号", "左方括号", "右方括号", "分号", "冒号",
        "句号", "逗号", "刀乐", "加号", "减号", "乘号", "除号", "百分号", "感叹号",
        "感叹号等于", "小于", "小于等于", "大于", "大于等于", "位与", "位或", "位异或",
        "问号", "等于", "加等于", "减等于", "乘等于", "除等于", "模等于", "位与等于",
        "位或等于", "位异或等于", "左移", "右移", "左移等于", "右移等于", "与与", "或或",
        "问问", "等于等于", "自增", "自减", "箭头", "省略号", "双冒"]

失败 = 0
if len(关键字) != len(关键字名):
    print("关键字数量不符:", len(关键字), len(关键字名)); 失败 += 1
if len(文本标志) != len(标志名):
    print("文本标志数量不符:", len(文本标志), len(标志名)); 失败 += 1

for i, (s, 名) in enumerate(zip(关键字, 关键字名)):
    if 枚.get(名) != i + 1:
        print("关键字 id 不符:", s, 名, "枚举=", 枚.get(名), "期望=", i + 1); 失败 += 1
for i, (s, 名) in enumerate(zip(文本标志, 标志名)):
    if 枚.get(名) != 101 + i:
        print("文本标志 id 不符:", s, 名, "枚举=", 枚.get(名), "期望=", 101 + i); 失败 += 1

print("校验完成：失败项 =", 失败)
sys.exit(1 if 失败 else 0)